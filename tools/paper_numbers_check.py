"""Check that every number in the paper's .tex files comes from results/P7/TABLES.md (or a short whitelist).

Usage: python3 -I tools/paper_numbers_check.py [tex dir, default paper/v2] [tables, default results/P7/TABLES.md]
       (also used for docs/synthesis_report: python3 -I tools/paper_numbers_check.py docs/synthesis_report)
Exit 1 if any number fails. Prints every number with the TABLES.md line it matched, so each match can be audited.
Tested by tests/test_paper_numbers_check.py (planted old-paper figures must fail).

Two forms are accepted in the .tex:
- a plain number must equal a TABLES.md value exactly (636.1 matches 636.1, not 636 or 636.10);
- a rounded number is written \\rnd{shown}{source} (the macro typesets only `shown`): `source` must equal a TABLES.md
  value exactly, and `shown` must be `source` rounded half-up to the decimals written in `shown`
  (\\rnd{636}{636.1}, \\rnd{71.8}{71.8034}). So every rounding names the value it was rounded from.

What counts as a number in the .tex: a digit sequence (thousands commas allowed, optional decimals) that is not glued
to a letter or underscore on its left (H100, P5e, NanGate45, d16_m0 are names). Removed before scanning: comments;
tikzpicture environments; verbatim environments (shell commands, not results); option lists after
\\begin{env} (layout and colours); optional [...] arguments; the arguments of layout/reference commands (label, ref, cite,
includegraphics, usepackage, url, ...); tabular column specs; lengths such as 0.5\\columnwidth or 3pt. Signs are
ignored (-0.0357 matches 0.0357).
TABLES.md values: digit sequences not glued to a letter (zipf0.85 is a name), up to the heading "## Older evidence":
that section holds old figures that were not reproduced (and some that are contradicted), and the paper may not use it.
The default (TABLES.md) mode is kept for docs/synthesis_report and tests/test_paper_numbers_check.py; paper/v2 uses
the macro mode below (MACROS_DOC).
"""
import re
import sys
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

WHITELIST = {'2014': 'year (Criteo challenge)'}
STOP = '## Older evidence'
DROP_ARG = ('label', 'ref', 'eqref', 'cite', 'includegraphics', 'usepackage', 'documentclass', 'bibliography',
            'bibliographystyle', 'input', 'url', 'vspace', 'hspace', 'setlength', 'addtolength', 'cmidrule',
            'multicolumn', 'multirow', 'IEEEoverridecommandlockouts', 'path', 'src', 'linewidth', 'arraystretch',
            'renewcommand', 'newcommand', 'DeclareUrlCommand', 'fontsize', 'texttt', 'begin')
NUM = re.compile(r'(?<![A-Za-z_\d.])\d[\d,]*(?:\.\d+)?(?![\d])')
RND = re.compile(r'\\rnd\{([^{}]*)\}\{([^{}]*)\}')


def norm(s):
    return s.strip().lstrip('-').lstrip('\u2212').rstrip(',').replace(',', '').replace('{', '').replace('}', '')


def decimals(v):
    return len(v.split('.')[1]) if '.' in v else 0


def rounded(v, k):
    return str(Decimal(v).quantize(Decimal(1).scaleb(-k), rounding=ROUND_HALF_UP))


def index(tables):
    where = {}
    for i, ln in enumerate(tables.read_text().splitlines(), 1):
        if ln.startswith(STOP):
            break
        for m in NUM.finditer(ln):
            where.setdefault(norm(m.group(0)), i)
    return where


def clean(tex):
    tex = re.sub(r'(?<!\\)%.*', '', tex)
    tex = re.sub(r'\\begin\{tikzpicture\}.*?\\end\{tikzpicture\}', ' ', tex, flags=re.S)
    tex = re.sub(r'\\begin\{verbatim\}.*?\\end\{verbatim\}', ' ', tex, flags=re.S)
    tex = re.sub(r'(\\begin\{[A-Za-z*]+\})\[(?:[^\[\]{}]|\{(?:[^{}]|\{[^{}]*\})*\})*\]', r'\1', tex)  # environment options
    tex = tex.replace('{,}', ',').replace('\\,', ' ').replace('$', ' ')
    tex = re.sub(r'(\\begin\{tabular\*?\})(\{[^}]*\})?\{[^{}]*(\{[^{}]*\}[^{}]*)*\}', r'\1', tex)
    for _ in range(3):
        tex = re.sub(r'\\(' + '|'.join(DROP_ARG) + r')\*?(\[[^\]]*\])*(\{[^{}]*\})?(\{[^{}]*\})?', ' ', tex)
    tex = re.sub(r'(?<=\\)[A-Za-z]+\[[^\]]*\]', '', tex)
    tex = re.sub(r'\d*\.?\d+\s*\\(columnwidth|textwidth|linewidth|baselineskip)', ' ', tex)
    tex = re.sub(r'(?<![A-Za-z_\d])\d*\.?\d+(pt|in|cm|mm|em|ex)\b', ' ', tex)
    tex = re.sub(r'\\[A-Za-z]+', ' ', tex)
    return tex


MACROS_DOC = """
Macro mode (paper/v2 since 2026-11-19): python3 -I tools/paper_numbers_check.py --macros [tex dir, default paper/v2]
Every number must be written as \\R{key}; macros.tex (generated by tools/make_paper_macros.py) defines each key and
names its source file and line. The check runs per sentence, table cell and caption of every .tex file except
macros.tex, and fails on: any digit outside \\R{...} (identifiers listed in NAMES are allowed); a key that macros.tex
does not define; a definition without a results/ source comment; the word TSMC; a stale macros.tex
(make_paper_macros.py --check). It prints each failing sentence with its numbers, and the number of \\todo{} left.
It also fails a prose paragraph or list item with more than PAR_MAX distinct numbers, or an abstract with more than
ABSTRACT_MAX (tables, figures and captions are exempt).
"""
NAMES = [                                    # identifiers that contain digits but are not results
    (r'28nm', 'technology node name'),
    (r'(\\texttt\{COUNTER\\_MODE\}|[Mm]odes?)(~|\s)+[0-2]\b', 'COUNTER_MODE value (an RTL parameter name)'),
    (r'victim\$\{\}\+1\$', 'RTL rule ptr = victim + 1'),
]


def _drop_tikz_coords(m):
    body = m.group(0)
    for _ in range(3):
        body = re.sub(r'\[[^\[\]]*\]', ' ', body)            # options: positions, styles, lengths
        body = re.sub(r'\([^()]*\)', ' ', body)              # coordinates and node names
    return body


def macro_clean(tex):
    tex = re.sub(r'(?<!\\)%.*', '', tex)
    tex = re.sub(r'\\begin\{tikzpicture\}.*?\\end\{tikzpicture\}', _drop_tikz_coords, tex, flags=re.S)
    for rx, _ in NAMES:
        tex = re.sub(rx, ' NAME ', tex)
    tex = re.sub(r'\\R\{[^{}]+\}', ' NUM ', tex)
    tex = re.sub(r'\\cmidrule(\([^)]*\))?\{[^{}]*\}', ' ', tex)
    tex = re.sub(r'\\(begin|end)\{tikzpicture\}', ' ', tex)
    tex = re.sub(r'(\\begin\{[A-Za-z*]+\})\[(?:[^\[\]{}]|\{(?:[^{}]|\{[^{}]*\})*\})*\]', r'\1', tex)
    tex = tex.replace('\\,', ' ').replace('$', ' ')
    tex = re.sub(r'(\\begin\{tabular\*?\})(\{[^}]*\})?\{[^{}]*(\{[^{}]*\}[^{}]*)*\}', r'\1', tex)
    for _ in range(3):
        tex = re.sub(r'\\(' + '|'.join(DROP_ARG) + r')\*?(\[[^\]]*\])*(\{[^{}]*\})?(\{[^{}]*\})?', ' ', tex)
    tex = re.sub(r'(?<=\\)[A-Za-z]+\[[^\]]*\]', '', tex)
    tex = re.sub(r'\\\\\[[^\]]*\]', r'\\\\', tex)
    tex = re.sub(r'\d*\.?\d+\s*\\(columnwidth|textwidth|linewidth|baselineskip)', ' ', tex)
    tex = re.sub(r'(?<![A-Za-z_\d])\d*\.?\d+(pt|in|cm|mm|em|ex)\b', ' ', tex)
    return tex


PAR_MAX, ABSTRACT_MAX = 3, 6        # distinct \R{} numbers per prose paragraph / in the abstract (authors' rule)


def paragraph_counts(nocom):
    """(label, distinct keys) for the abstract and every prose paragraph or list item; floats, tables, captions and
    the bibliography are not prose and are skipped."""
    out = []
    m = re.search(r'\\begin\{abstract\}(.*?)\\end\{abstract\}', nocom, re.S)
    if m:
        out.append(('abstract', sorted(set(re.findall(r'\\R\{([^{}]+)\}', m.group(1)))), ABSTRACT_MAX))
        nocom = nocom.replace(m.group(0), ' ')
    nocom = re.sub(r'\\begin\{(figure|table)\*?\}.*?\\end\{\1\*?\}', ' ', nocom, flags=re.S)
    nocom = re.sub(r'\\(title|author|maketitle|bibliography|bibliographystyle)\b(\{(?:[^{}]|\{[^{}]*\})*\})?', ' ', nocom)
    for par in re.split(r'\n\s*\n|\\item\b', nocom):
        keys = sorted(set(re.findall(r'\\R\{([^{}]+)\}', par)))
        if keys:
            out.append((' '.join(par.split())[:90], keys, PAR_MAX))
    return out


def macro_mode(root):
    import subprocess
    bad, nsent, nuse = [], 0, 0
    gen = subprocess.run([sys.executable, '-I', str(Path(__file__).resolve().parent / 'make_paper_macros.py'),
                          '--check'], capture_output=True, text=True)
    if gen.returncode:
        bad.append(('macros.tex', gen.stdout.strip()))
    defs = {}
    for i, ln in enumerate((root / 'macros.tex').read_text().splitlines(), 1):
        if not ln.startswith('\\defnum'):
            continue
        m = re.match(r'\\defnum\{([^{}]+)\}\{(.*)\}%\s*(\S.*)$', ln)
        if not m or 'results/' not in m.group(3):
            bad.append(('macros.tex', f'line {i}: definition without a results/ source comment'))
            continue
        defs[m.group(1)] = (m.group(2), m.group(3))
    todos = 0
    for tex in sorted(p for p in root.glob('*.tex') if p.name != 'macros.tex'):
        raw = tex.read_text()
        body = raw.split('\\begin{document}', 1)[-1]
        nocom = re.sub(r'(?<!\\)%.*', '', body)
        todos += len(re.findall(r'\\todo\{', nocom))
        for label, keys, lim in paragraph_counts(nocom):
            if len(keys) > lim:
                bad.append((tex.name, f'{len(keys)} numbers (limit {lim}) in paragraph: {label}  keys: {keys}'))
        if re.search(r'tsmc', nocom, re.I):
            bad.append((tex.name, 'the word TSMC appears (withdrawn numbers)'))
        for k in re.findall(r'\\R\{([^{}]+)\}', nocom):
            nuse += 1
            if k not in defs:
                bad.append((tex.name, f'\\R{{{k}}} is not defined in macros.tex'))
        units = re.split(r'(?<=[.!?])\s+(?=[A-Z\\(])|\\\\|&|\n\s*\n|\\caption|\\item|\\section|\\subsection',
                         macro_clean(body))
        for u in units:
            text = re.sub(r'\\[A-Za-z]+', ' ', u)
            if not text.strip():
                continue
            nsent += 1
            nums = [m.group(0) for m in NUM.finditer(text)]
            if nums:
                bad.append((tex.name, f'numbers {nums} without a macro in: {" ".join(u.split())[:160]}'))
    for name, why in bad:
        print(f'FAIL  {name}: {why}')
    print(f'\n{nsent} sentences, cells and captions checked; {nuse} \\R{{}} uses of {len(defs)} macros; '
          f'{todos} \\todo{{}} left; {len(bad)} failed.')
    sys.exit(1 if bad else 0)


def main():
    if len(sys.argv) > 1 and sys.argv[1] == '--macros':
        macro_mode(Path(sys.argv[2] if len(sys.argv) > 2 else 'paper/v2'))
    root = Path(sys.argv[1] if len(sys.argv) > 1 else 'paper/v2')
    tables = Path(sys.argv[2] if len(sys.argv) > 2 else 'results/P7/TABLES.md')
    where = index(tables)
    bad, n = [], 0

    def fail(name, shown, why):
        bad.append((name, shown))
        print(f'FAIL      {name}: {shown:>14}  {why}')

    for tex in sorted(root.glob('*.tex')):
        text = re.sub(r'(?<!\\)%.*', '', tex.read_text())
        text = text.replace(r'\newcommand{\rnd}[2]{#1}', ' ')
        for m in RND.finditer(text):                                     # rounded numbers
            n += 1
            shown, srcv = norm(m.group(1)), norm(m.group(2))
            if srcv not in where:
                fail(tex.name, m.group(1), f'\\rnd source {m.group(2)} not in TABLES.md')
            elif rounded(srcv, decimals(shown)) != shown or decimals(srcv) < decimals(shown):
                fail(tex.name, m.group(1), f'is not {m.group(2)} rounded to {decimals(shown)} decimals')
            else:
                print(f'rounded   {tex.name}: {m.group(1):>14}  from {m.group(2)}, TABLES.md:{where[srcv]}')
        for ln in clean(RND.sub(' ', text)).splitlines():               # plain numbers
            for m in NUM.finditer(ln):
                v = norm(m.group(0))
                if not v:
                    continue
                n += 1
                if v in where:
                    print(f'ok        {tex.name}: {m.group(0):>14}  TABLES.md:{where[v]}')
                elif v in WHITELIST:
                    print(f'whitelist {tex.name}: {m.group(0):>14}  {WHITELIST[v]}')
                else:
                    fail(tex.name, m.group(0), f'not in TABLES.md; context: {ln.strip()[:90]}')
    print(f'\n{n} numbers checked against {tables} (up to "{STOP}"); {len(bad)} failed.')
    sys.exit(1 if bad else 0)


if __name__ == '__main__':
    main()
