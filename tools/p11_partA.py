"""P11 part A: full-trace shared-cache hit rates, v2 rule (RTL-exact mode 0) vs v3 rule (Rotate-victim mode 0).

Usage: python -I tools/p11_partA.py > results/P11/PARTA.md
Reads results/P11/cluster/rows_<N>/shared_cache_results.json (cluster/jobs/p11_shared.sbatch; one cache shared by all
26 tables, P9 stream and order). Hit rate = hits / accesses (the "hit_rate" field, percent). For v3 vs v2 it also counts
the tables whose own hits (inside the shared cache) are lower under v3, and the sum of those per-table losses.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LFU = 'LFU (gem5 LFURP — reset on eviction)'
POL = [('LRU', 'LRU'), (LFU, 'LFU-reset (oldest)'), ('RTL-exact mode 0', 'v2: RTL-exact m0'),
       ('Rotate-victim mode 0', 'v3: Rotate-victim m0')]


def main():
    out = ['# P11 part A: full-trace hit rates, one cache shared by all 26 tables', '',
           'Generated by `tools/p11_partA.py` from `results/P11/cluster/rows_<N>/shared_cache_results.json`. 256 entries '
           'is the reproduction check (`ref_check.txt`: P11_REF_CHECK PASS at 2M and 10M).', '',
           '| rows | entries | accesses | ' + ' | '.join(f'{n} hits (rate)' for _, n in POL) +
           ' | v3 - v2 hits | tables with v3 < v2 (of 26) | v3 hits lost on those tables | v3 == LFU-reset per table |',
           '|---|---|---|' + '---|' * (len(POL) + 4)]
    for n in (2000000, 10000000):
        d = json.loads((ROOT / f'results/P11/cluster/rows_{n}/shared_cache_results.json').read_text())
        acc = d['meta']['accesses']
        for c in ('16', '64', '256'):
            r = d['results'][c]
            v2, v3 = r['RTL-exact mode 0'], r['Rotate-victim mode 0']
            loss = [b['hits'] - a['hits'] for a, b in zip(v3['per_table'], v2['per_table']) if a['hits'] < b['hits']]
            out.append(f'| {n:,} | {c} | {acc:,} | ' + ' | '.join(f"{r[p]['hits']:,} ({r[p]['hit_rate']:.4f}%)" for p, _ in POL)
                       + f" | {v3['hits'] - v2['hits']:+,} | {len(loss)} | {sum(loss):,} | "
                       f"{'yes' if v3['per_table'] == r[LFU]['per_table'] else 'no'} |")
    print('\n'.join(out))


if __name__ == '__main__':
    main()
