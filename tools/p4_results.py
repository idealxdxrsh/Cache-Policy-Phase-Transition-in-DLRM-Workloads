"""Build results/P4/RESULTS.md from the P4 GPU job output only.

Usage: python -I tools/p4_results.py results/P4
Reads <gpu>_<jobid>/results.csv for h100_413621 and h200_413622.
Launch-bound flag 'L': CPU wall per iteration at this batch is within 5% of the
wall at batch 64 for the same (rows, dim, pattern), i.e. the iteration time does
not grow with the work. This is a timing criterion, not a profiler measurement.
"""
import csv
import sys
from pathlib import Path

RUNS = [('H100', 'h100_413621'), ('H200', 'h200_413622')]
PATTERNS = ['uniform', 'zipf0.6', 'zipf0.85', 'zipf1.1', 'criteo']
BATCHES = [64, 128, 256, 512, 1024, 2048, 4096, 8192]
LB_TOL = 1.05


def f(x, k):
    return float(x[k])


def main():
    root = Path(sys.argv[1])
    out = ['# P4 results: EmbeddingBag (26 tables) vs MLP, CUDA events, 20 warmup + 100 timed iterations',
           '', 'Generated by `tools/p4_results.py` from `results/P4/<gpu>_<jobid>/results.csv`. fp32, no_grad,',
           'pooling 1. ms values are medians over the 100 timed iterations. "wall" = CPU wall ms per iteration',
           '(launch loop for 100 iterations + one final synchronize, / 100). "L" = launch-bound by the criterion',
           f'in the script docstring (wall within {LB_TOL - 1:.0%} of the batch-64 wall for the same rows/dim/pattern).',
           'No GPU counters were collected (see SUMMARY.md, ncu), so nothing here says why a kernel takes its time.', '']
    for gpu, d in RUNS:
        rows = list(csv.DictReader(open(root / d / 'results.csv')))
        ok = [x for x in rows if x['status'] == 'ok']
        sk = [x for x in rows if x['status'] == 'skipped']
        out += [f'## {gpu} (`results/P4/{d}/results.csv`): {len(ok)} ok, {len(sk)} skipped of {len(rows)}', '']
        for x in sorted({(x['rows'], x['dim'], x['note']) for x in sk}):
            out.append(f'- skipped rows={x[0]} dim={x[1]}: {x[2]}')
        timed = sum(f(x, 'cpu_wall_ms_per_iter') * int(x['iters']) for x in ok)
        out.append(f'- sum over ok configs of CPU wall per iteration x timed iterations: {timed / 1e3:.4f} s')
        out.append('')
        key = {(x['rows'], x['dim'], x['pattern'], int(x['batch'])): x for x in ok}
        for title, fmt in [('Median embedding share emb/(emb+mlp), "L" = launch-bound',
                            lambda x, lb: f"{f(x, 'emb_share_median'):.4f}{' L' if lb else ''}"),
                           ('Median embedding ms / MLP ms / CPU wall ms per iteration',
                            lambda x, lb: f"{f(x, 'emb_ms_median'):.4f} / {f(x, 'mlp_ms_median'):.4f} / "
                                          f"{f(x, 'cpu_wall_ms_per_iter'):.4f}")]:
            out += [f'### {gpu}: {title}', '',
                    '| rows | dim | pattern | ' + ' | '.join(f'B={b}' for b in BATCHES) + ' |',
                    '|---|---|---|' + '---|' * len(BATCHES)]
            for r, dm in sorted({(k[0], k[1]) for k in key}, key=lambda t: (int(t[0]), int(t[1]))):
                for p in PATTERNS:
                    base = f(key[r, dm, p, 64], 'cpu_wall_ms_per_iter')
                    cells = [fmt(key[r, dm, p, b], f(key[r, dm, p, b], 'cpu_wall_ms_per_iter') <= LB_TOL * base)
                             for b in BATCHES]
                    out.append(f'| {int(r):,} | {dm} | {p} | ' + ' | '.join(cells) + ' |')
            out.append('')
        # spread across patterns and across row counts
        out += [f'### {gpu}: spread of median embedding ms', '',
                '| rows | dim | batch | min over 5 patterns | max over 5 patterns |', '|---|---|---|---|---|']
        for r, dm in sorted({(k[0], k[1]) for k in key}, key=lambda t: (int(t[0]), int(t[1]))):
            for b in BATCHES:
                v = [f(key[r, dm, p, b], 'emb_ms_median') for p in PATTERNS]
                out.append(f'| {int(r):,} | {dm} | {b} | {min(v):.4f} | {max(v):.4f} |')
        out.append('')
    (root / 'RESULTS.md').write_text('\n'.join(out))
    print(f'Saved: {root / "RESULTS.md"}')


if __name__ == '__main__':
    main()
