"""P11 part B: rtl/v3 synthesis results next to rtl-v2-final, both with the P5e flow. NanGate45, not TSMC. Pre-layout.

Usage: python -I tools/p11_synth_report.py [liberty]   (prints Markdown; run by cluster/p11_driver.sh report)
v2 = results/P5e/new/d<D>_m<M>_<F>MHz (rtl-v2-final), v3 = results/P11/synth/d<D>_m<M>_<F>MHz (rtl/v3); both parsed
with tools/p5_results.row (cells and flip-flops from stat.txt, area = `stat -liberty` chip area, Fmax = 1 / (period -
WNS) from sta.txt, no multicycle exceptions). Change = (v3 - v2) / v2.
Noise floors (1 GHz netlists only; none exists at 500 MHz), spread = (max - min) / min over 8 designs with the same
logic, recomputed here from their files with the same formula as tools/p5d_noise.py:
  P5d floor = tools/p5d_noise.DESIGNS (results/P5d/NOISE.md, old flow);
  P5e floor = the same 8 designs with the P5e flow (results/P5e/new + results/P5e/noise/*; results/P5e/COMPARE.md s.3).
A change "exceeds" a floor when |change| > spread at that depth and mode. Fmax, area and cell-count floors are each
the spread of that quantity.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from p5_results import row  # noqa: E402
from p5d_noise import DESIGNS as P5D_DESIGNS, NULLS  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
LIB = sys.argv[1] if len(sys.argv) > 1 else str(Path.home() / 'eda/pdk/nangate45/NangateOpenCellLibrary_typical.lib')
P5E_DESIGNS = ([('final', 'results/P5e/new')] + [(f'final {n}', f'results/P5e/noise/final_{n}') for n in NULLS]
               + [('packed', 'results/P5e/noise/packed')] + [(f'packed {n}', f'results/P5e/noise/packed_{n}') for n in NULLS])


def fmax(r):
    return 1e3 / r['minp'] if r['minp'] else None


def spread(designs, d, m):
    rows = [row(ROOT / p / f'd{d}_m{m}_1000MHz', LIB) for _, p in designs]
    out = {}
    for k, f in (('fmax', fmax), ('area', lambda r: r['area']), ('cells', lambda r: r['cells'])):
        v = [f(r) for r in rows]
        out[k] = (max(v) - min(v)) / min(v) * 100
    return out


def pc(a, b):
    return (b - a) / a * 100


def main():
    out = ['# P11 synthesis: rtl/v3 (Rotate-victim in mode 0) vs rtl-v2-final, P5e flow unchanged. NanGate45, not TSMC; pre-layout',
           '', 'Generated by `tools/p11_synth_report.py` from `results/P5e/new/*` (v2) and `results/P11/synth/*` (v3): '
           '`stat.txt`, `sta.txt`. Area = sum of liberty cell areas (`stat -liberty`), not a placed area. No power numbers. '
           'Fmax = 1 / (period - WNS), pre-layout, no multicycle exceptions. Change = (v3 - v2) / v2.', '',
           '| depth | mode | clock | cells v2 -> v3 (change) | flip-flops v2 -> v3 | area um^2 v2 -> v3 (change) | '
           'Fmax MHz v2 -> v3 (change) | WNS ns v2 -> v3 | other slew/cap violators v2 -> v3 |',
           '|---|---|---|---|---|---|---|---|---|']
    res = {}
    for d in (16, 64, 256):
        for m in (0, 1):
            for f in (1000, 500):
                a, b = (row(ROOT / p / f'd{d}_m{m}_{f}MHz', LIB) for p in ('results/P5e/new', 'results/P11/synth'))
                res[d, m, f] = (a, b)
                fa, fb = fmax(a), fmax(b)
                fm = (f'{fa:.1f} -> {fb:.1f} ({pc(fa, fb):+.2f}%)' if fa and fb else
                      f'{f"{fa:.1f}" if fa else "met"} -> {f"{fb:.1f}" if fb else "met"}')
                out.append(f'| {d} | {m} | {f} MHz | {a["cells"]:,} -> {b["cells"]:,} ({pc(a["cells"], b["cells"]):+.2f}%) | '
                           f'{a["ffs"]:,} -> {b["ffs"]:,} ({b["ffs"] - a["ffs"]:+d}) | {a["area"]:.3f} -> {b["area"]:.3f} '
                           f'({pc(a["area"], b["area"]):+.2f}%) | {fm} | {a["wns"]:.4f} -> {b["wns"]:.4f} | '
                           f'{len(a["other"])} -> {len(b["other"])} |')
    out += ['', '## Change vs flow noise floor, 1 GHz netlists (|change| > spread = exceeds the floor)', '',
            'P5d floor: the 8 same-logic designs of `results/P5d/NOISE.md` (old flow), reused as asked. P5e floor: the same 8 '
            'designs with the P5e flow, the flow used here (`results/P5e/COMPARE.md` s.3). Spreads recomputed from their '
            '`stat.txt` / `sta.txt` files.', '',
            '| depth | mode | Fmax change | Fmax spread P5d / P5e | exceeds P5d / P5e | area change | area spread P5d / P5e | '
            'exceeds P5d / P5e | cells change | cells spread P5d / P5e | exceeds P5d / P5e |',
            '|---|---|---|---|---|---|---|---|---|---|---|']
    yn = lambda c, s: 'yes' if abs(c) > s else 'no'
    for d in (16, 64, 256):
        for m in (0, 1):
            a, b = res[d, m, 1000]
            s5d, s5e = spread(P5D_DESIGNS, d, m), spread(P5E_DESIGNS, d, m)
            ch = {'fmax': pc(fmax(a), fmax(b)), 'area': pc(a['area'], b['area']), 'cells': pc(a['cells'], b['cells'])}
            out.append(f'| {d} | {m} | ' + ' | '.join(
                f'{ch[k]:+.2f}% | {s5d[k]:.2f}% / {s5e[k]:.2f}% | {yn(ch[k], s5d[k])} / {yn(ch[k], s5e[k])}'
                for k in ('fmax', 'area', 'cells')) + ' |')
    out += ['', '500 MHz netlists: no noise floor was measured at 500 MHz (P5d and P5e measured 1 GHz only); only met / '
            'not met and WNS are reported above.', '']
    print('\n'.join(out))


if __name__ == '__main__':
    main()
