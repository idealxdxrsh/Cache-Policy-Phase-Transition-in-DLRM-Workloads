"""Build results/P5/RESULTS.md from the P5 Yosys + OpenSTA output only.

Usage: python -I tools/p5_results.py results/P5 <liberty>
Reads d<D>_m<M>_<F>MHz/{stat.txt, sta.txt, time_yosys.txt, time_sta.txt}, netlists.sha256,
and the per-cell `area` of the flip-flop cells from the liberty file.
NanGate45, not TSMC. Pre-layout. No power numbers (none are produced by the flow).
"min period" = clock period - WNS (setup, ideal clock, reg/port paths; rst_n excluded) and
"Fmax" = 1 / min period: derived from the STA slack of that netlist, labelled pre-layout.
"""
import re
import sys
from pathlib import Path

DEPTHS = [16, 64, 256]
MODES = [0, 1]
FREQS = [1000, 500]


def grab(pat, text, cast=float):
    m = re.search(pat, text, re.M)
    return cast(m.group(1)) if m else None


def elapsed(path):
    return grab(r'Elapsed \(wall clock\) time \(h:mm:ss or m:ss\): (\S+)', path.read_text(), str)


def cell_area(lib, cell):
    text = Path(lib).read_text()
    i = text.index(f'cell ({cell})')
    return float(re.search(r'area\s*:\s*([\d.]+)', text[i:]).group(1))


def row(d, lib):
    stat, sta = (d / 'stat.txt').read_text(), (d / 'sta.txt').read_text()
    cells = grab(r'Number of cells:\s+(\d+)', stat, int)
    ff = {c: int(n) for c, n in re.findall(r'^\s+(S?DFF\w*)\s+(\d+)', stat, re.M)}
    ffs = sum(ff.values())
    ff_area = sum(n * cell_area(lib, c) for c, n in ff.items())
    area = grab(r"Chip area for module .*: ([\d.]+)", stat)
    period = grab(r'^PERIOD_NS (\S+)', sta)
    wns = grab(r'^wns max (\S+)', sta)
    tns = grab(r'^tns max (\S+)', sta)
    hold = grab(r'^worst slack min (\S+)', sta)
    maxblk = sta[sta.index('Path Type: max'):]
    arrival = grab(r'^\s+([\d.]+)\s+data arrival time', maxblk)
    viol = [ln.split()[0] for ln in sta.splitlines() if ln.rstrip().endswith('(VIOLATED)') and 'slack' not in ln]
    other = sorted({v for v in viol if v != 'rst_n'})
    minp = period - wns if wns < 0 else None
    return dict(cells=cells, ffs=ffs, ff_area=ff_area, area=area, period=period, wns=wns, tns=tns, hold=hold, arrival=arrival,
                minp=minp, other=other,
                t_yosys=elapsed(d / 'time_yosys.txt'), t_sta=elapsed(d / 'time_sta.txt'))


def main():
    root, lib = Path(sys.argv[1]), sys.argv[2]
    sha = dict(ln.split()[::-1] for ln in (root / 'netlists.sha256').read_text().splitlines())
    out = ['# P5 results: rtl/v2 LFU controller, Yosys 0.33 + NanGate45 typical liberty + OpenSTA 3.1.0',
           '', '**NanGate45, not TSMC. Pre-layout** (wire-load model 5K_hvratio_1_1, ideal clock, no placement or routing).',
           '**No power numbers** (no power step was run). Area = sum of liberty cell areas from `stat -liberty` (um^2),',
           'not a placed layout area. rst_n recovery/removal paths are excluded (`set_false_path -from rst_n`); the',
           'rst_n net itself violates max slew/cap in every run (no reset tree before layout).',
           'Generated by `tools/p5_results.py` from `results/P5/d<D>_m<M>_<F>MHz/{stat.txt,sta.txt,time_*.txt}`.',
           'Parameters: ADDR_WIDTH 20, VECTOR_WIDTH 128, COUNTER_WIDTH 6, GROUPS 16. abc target -D = clock period.', '',
           '| depth | mode | clock | cells | flip-flops | area um^2 | flip-flop area share | WNS ns | TNS ns | worst hold slack ns | '
           'critical arrival ns | min period ns (pre-layout) | Fmax MHz (pre-layout) | other slew/cap/fanout violators | '
           'yosys wall | sta wall |',
           '|' + '---|' * 16]
    for dd in DEPTHS:
        for m in MODES:
            for f in FREQS:
                d = root / f'd{dd}_m{m}_{f}MHz'
                if not (d / 'sta.txt').exists():
                    out.append(f'| {dd} | {m} | {f} MHz | missing |' + ' |' * 12)
                    continue
                r = row(d, lib)
                fmax = f'{1e3 / r["minp"]:.1f}' if r['minp'] else f'>= {f} (met)'
                minp = f'{r["minp"]:.4f}' if r['minp'] else 'met'
                out.append(f'| {dd} | {m} | {f} MHz | {r["cells"]:,} | {r["ffs"]:,} | {r["area"]:.3f} | {r["ff_area"] / r["area"]:.4f} | {r["wns"]:.4f} | '
                           f'{r["tns"]:.4f} | {r["hold"]:.4f} | {r["arrival"]:.4f} | {minp} | {fmax} | '
                           f'{len(r["other"])} | {r["t_yosys"]} | {r["t_sta"]} |')
    out += ['', 'Netlist sha256, 1000 MHz vs 500 MHz target (`netlists.sha256`; netlists are not committed):', '']
    for dd in DEPTHS:
        for m in MODES:
            a, b = (sha.get(f'd{dd}_m{m}_{f}MHz/netlist.v') for f in FREQS)
            out.append(f'- depth {dd} mode {m}: {"identical" if a and a == b else "different"}')
    out += ['', 'Critical (max) path start/end points per run are in each `sta.txt` (`report_checks -path_delay max`).', '']
    (root / 'RESULTS.md').write_text('\n'.join(out))
    print(f'Saved: {root / "RESULTS.md"}')


if __name__ == '__main__':
    main()
