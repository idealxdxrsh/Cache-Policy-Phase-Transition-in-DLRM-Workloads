"""P5e tables: old versus new ABC flow on rtl-v2-final, ABC's own delay estimate, and the noise floor.
NanGate45, not TSMC. Pre-layout.

Usage: python -I tools/p5e_report.py <liberty>   (prints Markdown)
Old flow = results/P5d (synthesis/p5/synth.ys.in); new flow = results/P5e/new (synthesis/p5e/synth_td.ys.in).
"ABC estimate" = Delay of the last `stime` line in the yosys log (ABC's own timer on the combinational logic it
maps, with the wire load it reports there). "Identical" compares the 1 GHz and 500 MHz netlists with the lines
holding the source path removed (netlist.v, not committed). Fmax = 1 / (period - WNS).
"""
import gzip
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from p5_results import row  # noqa: E402
from p5_critical_path import q_name  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
NULLS = ['null_tagcmp_swap', 'null_hitor_swap', 'null_stageB_gt']
OLD_NOISE = ([('final', 'results/P5d')] + [(f'final {n}', f'results/P5d/noise/{n}') for n in NULLS]
             + [('packed', 'results/P5d/attempt1_packed_vectors')]
             + [(f'packed {n}', f'results/P5d/attempt1_packed_vectors/noise/{n}') for n in NULLS])
NEW_NOISE = ([('final', 'results/P5e/new')] + [(f'final {n}', f'results/P5e/noise/final_{n}') for n in NULLS]
             + [('packed', 'results/P5e/noise/packed')]
             + [(f'packed {n}', f'results/P5e/noise/packed_{n}') for n in NULLS])
EXPLAIN = ['results/P5', 'results/P5b', 'results/P5c/tree_copies', 'results/P5d', 'results/P5e/new']
RUNS = [(d, m) for d in (16, 64, 256) for m in (0, 1)]


def log_text(run):
    p = run / 'yosys.log.gz'
    return gzip.open(p, 'rt').read() if p.exists() else (run / 'yosys.log').read_text()


def abc_est(run):
    lines = re.findall(r'ABC: WireLoad = "([^"]*)".*Delay =\s*([\d.]+) ps', log_text(run))
    wl, dl = lines[-1]
    return wl, float(dl)


def identical(base, d, m):
    a, b = (base / f'd{d}_m{m}_{f}MHz/netlist.v' for f in (1000, 500))
    if not (a.exists() and b.exists()):
        return 'netlist not present'
    strip = lambda p: [ln for ln in p.read_text().splitlines() if '/home/' not in ln]  # noqa: E731
    return 'yes' if strip(a) == strip(b) else 'no'


def fmax(r):
    return 1e3 / r['minp'] if r['minp'] else None


def fm(r):
    f = fmax(r)
    return f'{f:.1f}' if f else f'met (WNS {r["wns"]:.4f})'


def main():
    lib = sys.argv[1]
    o = ['# P5e: old vs new ABC flow on rtl-v2-final — NanGate45, not TSMC; pre-layout; no power numbers', '',
         'Generated by `tools/p5e_report.py` from `<run>/{stat.txt,sta.txt,yosys.log.gz}` under the listed result',
         'directories. Old flow: `synthesis/p5/synth.ys.in`; new flow: `synthesis/p5e/synth_td.ys.in` +',
         '`synthesis/p5e/abc_td.script.in`. Fmax = 1 / (period - WNS) from OpenSTA (wire load 5K_hvratio_1_1).', '',
         '## 1. Does the clock target reach ABC? ABC estimate vs OpenSTA, 1 GHz and 500 MHz netlists', '',
         '| results | depth | mode | ABC wire load | ABC estimate ps @1 GHz / @500 MHz | 1 GHz and 500 MHz netlists identical | '
         'STA data arrival ns @1 GHz / @500 MHz |', '|' + '---|' * 7]
    for base in EXPLAIN:
        b = ROOT / base
        for d, m in RUNS:
            ests, arrs = [], []
            for f in (1000, 500):
                run = b / f'd{d}_m{m}_{f}MHz'
                wl, e = abc_est(run)
                ests.append(f'{e:.2f}')
                arrs.append(f'{row(run, lib)["arrival"]:.4f}')
            o.append(f'| `{base}` | {d} | {m} | {wl} | {" / ".join(ests)} | {identical(b, d, m)} | {" / ".join(arrs)} |')
    o += ['', '## 2. rtl-v2-final, old flow (`results/P5d`) -> new flow (`results/P5e/new`)', '',
          '| depth | mode | Fmax MHz (1 GHz netlist) | change | 500 MHz netlist: Fmax MHz or met | WNS @1 GHz ns | '
          'WNS @500 MHz ns | cells @1 GHz | area um^2 @1 GHz | other slew/cap/fanout violators @1 GHz | yosys wall @1 GHz |',
          '|' + '---|' * 11]
    for d, m in RUNS:
        old = {f: row(ROOT / f'results/P5d/d{d}_m{m}_{f}MHz', lib) for f in (1000, 500)}
        new = {f: row(ROOT / f'results/P5e/new/d{d}_m{m}_{f}MHz', lib) for f in (1000, 500)}
        ch = 100 * (fmax(new[1000]) / fmax(old[1000]) - 1)
        o.append(f'| {d} | {m} | {fm(old[1000])} -> {fm(new[1000])} | {ch:+.2f}% | {fm(old[500])} -> {fm(new[500])} | '
                 f'{old[1000]["wns"]:.4f} -> {new[1000]["wns"]:.4f} | {old[500]["wns"]:.4f} -> {new[500]["wns"]:.4f} | '
                 f'{old[1000]["cells"]:,} -> {new[1000]["cells"]:,} | {old[1000]["area"]:.3f} -> {new[1000]["area"]:.3f} | '
                 f'{len(old[1000]["other"])} -> {len(new[1000]["other"])} | '
                 f'{old[1000]["t_yosys"]} -> {new[1000]["t_yosys"]} |')
    o += ['', '## 3. Noise floor: Fmax MHz over 8 same-logic designs, 1 GHz netlists (designs as in `results/P5d/NOISE.md`)', '',
          '| flow | depth | mode | ' + ' | '.join(n for n, _ in NEW_NOISE) + ' | min | max | spread | distinct (cells, area) |',
          '|' + '---|' * (len(NEW_NOISE) + 7)]
    for d, m in RUNS:
        for flow, designs in (('old', OLD_NOISE), ('new', NEW_NOISE)):
            fs, maps = [], set()
            for _, p in designs:
                r = row(ROOT / p / f'd{d}_m{m}_1000MHz', lib)
                fs.append(fmax(r))
                maps.add((r['cells'], r['area']))
            lo, hi = min(fs), max(fs)
            o.append(f'| {flow} | {d} | {m} | ' + ' | '.join(f'{f:.1f}' for f in fs)
                     + f' | {lo:.1f} | {hi:.1f} | {100 * (hi - lo) / lo:.2f}% | {len(maps)} of {len(fs)} |')
    o += ['', '## 4. 500 MHz with the new flow: worst arrival vs the 2 ns period, and the new-flow noise spread', '',
          '| depth | mode | WNS @500 MHz ns | WNS as % of the 2 ns period | new-flow 1 GHz noise spread |', '|---|---|---|---|---|']
    for d, m in RUNS:
        r = row(ROOT / f'results/P5e/new/d{d}_m{m}_500MHz', lib)
        fs = [fmax(row(ROOT / p / f'd{d}_m{m}_1000MHz', lib)) for _, p in NEW_NOISE]
        o.append(f'| {d} | {m} | {r["wns"]:.4f} | {100 * -r["wns"] / 2:.2f}% | '
                 f'{100 * (max(fs) - min(fs)) / min(fs):.2f}% |')
    o += ['', '## 5. Worst paths before and after the multicycle exceptions (`tools/p5e_mcp.py`; `results/P5e/mcp/<flow>/<run>/sta.txt`)', '',
          '| flow | run | WNS ns without -> with exceptions | worst start register -> end register, without | '
          'worst start register -> end register, with |', '|---|---|---|---|---|']
    for flow, src in (('old', 'results/P5d'), ('new', 'results/P5e/new')):
        for d, m in RUNS:
            for f in (1000, 500):
                run = f'd{d}_m{m}_{f}MHz'
                a, b = ROOT / src / run, ROOT / f'results/P5e/mcp/{flow}/{run}'
                ends = [ends_of(x / 'sta.txt', a / 'netlist.v') for x in (a, b)]
                o.append(f'| {flow} | {run} | {row(a, lib)["wns"]:.4f} -> {wns_of(b / "sta.txt"):.4f} | '
                         f'{ends[0]} | {ends[1]} |')
    print('\n'.join(o))


def wns_of(sta):
    return float(re.search(r'^wns max (\S+)', sta.read_text(), re.M).group(1))


def ends_of(sta, netlist):
    t = sta.read_text()  # the max path is reported first (synthesis/p5/sta.tcl)
    sp = re.search(r'Startpoint: (\S+)', t).group(1)
    ep = re.search(r'Endpoint: (\S+)', t).group(1)
    return f'`{q_name(netlist, sp)}` -> `{q_name(netlist, ep)}`'


if __name__ == '__main__':
    main()
