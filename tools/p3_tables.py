"""Build results/P3/TABLES.md from the P3 result CSVs (no other inputs).

Usage: python -I tools/p3_tables.py results/P3
Reads rows_<N>/figs/hit_rates.csv and rows_<N>/figs/zipf_per_table.csv for
N in 2000000 and 10000000; prints the 256-vector LFU vs LRU comparison.
"""
import csv
import sys
from pathlib import Path

ROWS = (2000000, 10000000)
FOCUS = 256
LRU = 'LRU'
LFUS = ('LFU (persistent counters)', 'LFU (gem5 LFURP — reset on eviction)')


def load(root, n):
    d = root / f'rows_{n}' / 'figs'
    rates, policies, caps = {}, [], []
    with open(d / 'hit_rates.csv', newline='') as f:
        for r in csv.DictReader(f):
            p, c = r['policy'], int(r['capacity'])
            if p not in policies:
                policies.append(p)
            if c not in caps:
                caps.append(c)
            rates[p, c, r['table']] = (int(r['hits']), int(r['misses']), r['hit_rate_pct'])
    with open(d / 'zipf_per_table.csv', newline='') as f:
        zipf = list(csv.DictReader(f))
    return rates, policies, caps, zipf


def main():
    root = Path(sys.argv[1])
    data = {n: load(root, n) for n in ROWS}
    out = ['# P3 tables (generated by tools/p3_tables.py; do not edit)', '',
           'Hit rates are % of accesses; capacity is in vectors, one cache per table.',
           'Values are copied verbatim from the CSVs named above each table.', '']
    for n in ROWS:
        rates, policies, caps, zipf = data[n]
        src = f'results/P3/rows_{n}/figs'
        tables = [z['table'] for z in zipf]
        out += [f'## {n:,} rows', '',
                f'### Sweep, all tables combined (`{src}/hit_rates.csv`, table=all)', '',
                '| capacity | ' + ' | '.join(policies) + ' |',
                '|---:|' + '---:|' * len(policies)]
        for c in caps:
            out.append(f'| {c:,} | ' + ' | '.join(rates[p, c, 'all'][2] for p in policies) + ' |')
        out += ['', f'### Per-table hit rate at {FOCUS} vectors (`{src}/hit_rates.csv`; '
                'every other capacity is in the same file)', '',
                '| table | ' + ' | '.join(policies) + ' |',
                '|---:|' + '---:|' * len(policies)]
        for t in tables:
            out.append(f'| {t} | ' + ' | '.join(rates[p, FOCUS, t][2] for p in policies) + ' |')
        out += ['', f'### Per-table Zipf fit (`{src}/zipf_per_table.csv`)', '',
                '| table | column | accesses | unique | zipf_alpha | fit points |',
                '|---:|---:|---:|---:|---:|---:|']
        for z in zipf:
            out.append(f"| {z['table']} | {z['column']} | {z['accesses']} | {z['unique']} "
                       f"| {z['zipf_alpha'] or 'no fit (<10 ranks)'} | {z['zipf_fit_points']} |")
        out.append('')
        print(f'rows={n} capacity={FOCUS}')
        lh, lm, lr = rates[LRU, FOCUS, 'all']
        print(f'  {LRU}: hits={lh} misses={lm} rate={lr}')
        for p in LFUS:
            h, m, r = rates[p, FOCUS, 'all']
            win = sum(rates[p, FOCUS, t][0] > rates[LRU, FOCUS, t][0] for t in tables)
            tie = sum(rates[p, FOCUS, t][0] == rates[LRU, FOCUS, t][0] for t in tables)
            print(f'  {p}: hits={h} misses={m} rate={r} hits-LRU={h - lh} '
                  f'tables LFU>LRU={win} tie={tie} of {len(tables)}')
    (root / 'TABLES.md').write_text('\n'.join(out))


if __name__ == '__main__':
    main()
