"""Build results/P3b/RESULTS.md from the P3b shared-cache job output only.

Usage: python -I tools/p3b_results.py results/P3b
Reads rows_<N>/parts/*.csv (hits/misses per table) and
rows_<N>/shared_cache_results.json (meta: accesses per table, job info)
for N = 2000000 and 10000000. The large-table section is 2M only.
"""
import csv
import json
import sys
from pathlib import Path

N = 2000000
N10 = 10000000
LARGE = [2, 11, 20, 15, 3]      # results/P3/ANALYSIS.md: >= 150,000 unique ids at 2M and 10M
CAPS = [256, 1000, 10000, 100000]
LRU = 'LRU'
LFUS = ('LFU (persistent counters)', 'LFU (gem5 LFURP — reset on eviction)')
ORDER = (LRU, LFUS[1], LFUS[0], 'ARC', 'W-TinyLFU (Count-Min, window=1%)')
SHORT = {LRU: 'LRU', LFUS[0]: 'LFU persist', LFUS[1]: 'LFU reset (LFURP)', 'ARC': 'ARC',
         'W-TinyLFU (Count-Min, window=1%)': 'W-TinyLFU'}


def pct(a, b):
    return f'{a / b * 100:.4f}'


def load(root, n):
    d = root / f'rows_{n}'
    meta = json.load(open(d / 'shared_cache_results.json'))['meta']
    hits, tot = {}, {}
    for f in sorted((d / 'parts').glob('*.csv')):
        rows = list(csv.DictReader(open(f)))
        p, c = rows[0]['policy'], int(rows[0]['capacity'])
        hits[p, c] = {int(r['table']): int(r['hits']) for r in rows if r['table'] != 'all'}
        a = next(r for r in rows if r['table'] == 'all')
        tot[p, c] = (int(a['hits']), int(a['misses']))
    return meta, hits, tot


def rate(tot, p, c):
    return tot[p, c][0] / sum(tot[p, c]) * 100


def main():
    root = Path(sys.argv[1])
    meta, hits, tot = load(root, N)
    meta10, _, tot10 = load(root, N10)
    acc = meta['accesses_per_table']
    n_acc = sum(acc)
    large_acc = sum(acc[t] for t in LARGE)
    src = f'`results/P3b/rows_{N}/parts/*.csv`'
    o = ['# P3b results: ONE shared cache over all 26 tables, 2M and 10M rows', '',
         '**The first three sections are 2,000,000 Criteo rows only; 10M is in its own section.** '
         'Jobs 413067 (2M), 413106 (10M) (`results/P3b/jobs.txt`). '
         f'Generated by `tools/p3b_results.py` from {src} and '
         f'`results/P3b/rows_{N}/shared_cache_results.json`.',
         f'Trace: {meta["accesses"]:,} accesses, {meta["unique_keys"]:,} unique (table, id) keys, '
         f'order: {meta["order"]}. Capacity = total vectors in the one shared cache.',
         'Hit rates are % of all accesses. Not comparable 1:1 with P3, where "256" meant 26 private '
         '256-entry caches.', '',
         '## Total hit rate, shared cache, 2M rows', '',
         '| capacity | ' + ' | '.join(SHORT[p] for p in ORDER) + ' |',
         '|---:|' + '---:|' * len(ORDER)]
    for c in CAPS:
        o.append(f'| {c:,} | ' + ' | '.join(pct(tot[p, c][0], sum(tot[p, c])) for p in ORDER) + ' |')

    o += ['', '## Five large tables (2, 11, 20, 15, 3), 2M rows only', '',
          'Large = >= 150,000 unique ids at both 2M and 10M (`results/P3/ANALYSIS.md`). '
          f'They make up {pct(large_acc, n_acc)}% of accesses ({large_acc:,} of {n_acc:,}).', '',
          'Share of all hits that come from the five large tables (%):', '',
          '| capacity | ' + ' | '.join(SHORT[p] for p in ORDER) + ' |',
          '|---:|' + '---:|' * len(ORDER)]
    for c in CAPS:
        o.append(f'| {c:,} | ' + ' | '.join(
            pct(sum(hits[p, c][t] for t in LARGE), tot[p, c][0]) for p in ORDER) + ' |')
    o += ['', 'Hit rate within the five large tables (their hits / their accesses, %):', '',
          '| capacity | ' + ' | '.join(SHORT[p] for p in ORDER) + ' |',
          '|---:|' + '---:|' * len(ORDER)]
    for c in CAPS:
        o.append(f'| {c:,} | ' + ' | '.join(
            pct(sum(hits[p, c][t] for t in LARGE), large_acc) for p in ORDER) + ' |')

    lh = tot[LRU, 256][0]
    verdicts = []
    for p in LFUS:
        h = tot[p, 256][0]
        verdicts.append(f'- {SHORT[p]}: {pct(h, n_acc)}% vs LRU {pct(lh, n_acc)}% '
                        f'({h - lh:+,} hits): ' + ('beats LRU.' if h > lh else
                                                   'does NOT beat LRU.' if h < lh else 'ties LRU.'))
    o += ['', '## Does LFU beat LRU in the shared cache at 256 vectors? 2M rows', ''] + verdicts
    other = [f'{c:,}: ' + ', '.join(f'{SHORT[p]} {"+" if tot[p, c][0] > tot[LRU, c][0] else "-"}'
                                    for p in LFUS) for c in CAPS if c != 256]
    o += ['', 'Sign of (LFU hits - LRU hits) at the other capacities: ' + '; '.join(other) + '.']
    o += ['', '## 10M rows vs 2M rows (same code, job 413106)', '',
          f'10M trace: {meta10["accesses"]:,} accesses, {meta10["unique_keys"]:,} unique (table, id) keys '
          f'(`results/P3b/rows_{N10}/parts/*.csv`, `.../shared_cache_results.json`). '
          'Change is 10M minus 2M in percentage points.', '',
          '| capacity | policy | 2M hit % | 10M hit % | change (pp) |', '|---:|---|---:|---:|---:|']
    for c in CAPS:
        for p in ORDER:
            a, b = rate(tot, p, c), rate(tot10, p, c)
            o.append(f'| {c:,} | {SHORT[p]} | {a:.4f} | {b:.4f} | {b - a:+.4f} |')
    o += ['', '### At 10M rows, 256 vectors: does LFU beat LRU?', '']
    lh10 = tot10[LRU, 256][0]
    for p in (LFUS[1], LFUS[0]):
        h = tot10[p, 256][0]
        o.append(f'- {SHORT[p]}: {rate(tot10, p, 256):.4f}% vs LRU {rate(tot10, LRU, 256):.4f}% '
                 f'({h - lh10:+,} hits): ' + ('beats LRU.' if h > lh10 else
                                              'does NOT beat LRU.' if h < lh10 else 'ties LRU.'))
    o += ['', '### Persistent-counter LFU at 10,000 and 100,000 vectors, 2M vs 10M', '']
    for c in (10000, 100000):
        for n, t in ((N, tot), (N10, tot10)):
            best = max(ORDER, key=lambda p: t[p, c][0])
            other = max((p for p in ORDER if p != LFUS[0]), key=lambda p: t[p, c][0])
            o.append(f'- {c:,} vectors, {n // 1000000}M: LFU persist {rate(t, LFUS[0], c):.4f}%, '
                     f'vs LRU {rate(t, LFUS[0], c) - rate(t, LRU, c):+.4f} pp, '
                     f'vs best other ({SHORT[other]}) {rate(t, LFUS[0], c) - rate(t, other, c):+.4f} pp; '
                     f'best policy: {SHORT[best]}.')
    lose = [f'{c:,}' for c in CAPS if tot10[LFUS[0], c][0] < tot10[LRU, c][0]]
    o.append('- LFU persist is below LRU at 10M for capacities: ' + (', '.join(lose) or 'none') + '.')
    o += ['', '## Run', '',
          f'- Wall: parse {meta["wall_seconds"]["load"]:.1f} s, sweep {meta["wall_seconds"]["sweep"]:.1f} s '
          f'on {meta["workers"]} workers; whole job and peak memory in `results/P3b/rows_{N}/time.txt`.',
          f'- 10M: parse {meta10["wall_seconds"]["load"]:.1f} s, sweep {meta10["wall_seconds"]["sweep"]:.1f} s '
          f'on {meta10["workers"]} workers; whole job and peak memory in `results/P3b/rows_{N10}/time.txt`.',
          '- At both sizes the 20 part CSVs equal the JSON results, and per-table access counts equal '
          '`results/P3/rows_<N>/figs/zipf_per_table.csv` (checked before writing this file).', '']
    (root / 'RESULTS.md').write_text('\n'.join(o))


if __name__ == '__main__':
    main()
