"""Build results/P3b/RESULTS.md from the P3b shared-cache job output only.

Usage: python -I tools/p3b_results.py results/P3b
Reads rows_2000000/parts/*.csv (hits/misses per table) and
rows_2000000/shared_cache_results.json (meta: accesses per table, job info).
"""
import csv
import json
import sys
from pathlib import Path

N = 2000000
LARGE = [2, 11, 20, 15, 3]      # results/P3/ANALYSIS.md: >= 150,000 unique ids at 2M and 10M
CAPS = [256, 1000, 10000, 100000]
LRU = 'LRU'
LFUS = ('LFU (persistent counters)', 'LFU (gem5 LFURP — reset on eviction)')
ORDER = (LRU, LFUS[1], LFUS[0], 'ARC', 'W-TinyLFU (Count-Min, window=1%)')
SHORT = {LRU: 'LRU', LFUS[0]: 'LFU persist', LFUS[1]: 'LFU reset (LFURP)', 'ARC': 'ARC',
         'W-TinyLFU (Count-Min, window=1%)': 'W-TinyLFU'}


def pct(a, b):
    return f'{a / b * 100:.4f}'


def main():
    root = Path(sys.argv[1])
    d = root / f'rows_{N}'
    meta = json.load(open(d / 'shared_cache_results.json'))['meta']
    hits, tot = {}, {}
    for f in sorted((d / 'parts').glob('*.csv')):
        rows = list(csv.DictReader(open(f)))
        p, c = rows[0]['policy'], int(rows[0]['capacity'])
        hits[p, c] = {int(r['table']): int(r['hits']) for r in rows if r['table'] != 'all'}
        a = next(r for r in rows if r['table'] == 'all')
        tot[p, c] = (int(a['hits']), int(a['misses']))
    acc = meta['accesses_per_table']
    n_acc = sum(acc)
    large_acc = sum(acc[t] for t in LARGE)
    src = f'`results/P3b/rows_{N}/parts/*.csv`'
    o = ['# P3b results: ONE shared cache over all 26 tables, 2M rows only', '',
         f'**2,000,000 Criteo rows only (no 10M run).** Job 413067 (`results/P3b/jobs.txt`). '
         f'Generated by `tools/p3b_results.py` from {src} and '
         f'`results/P3b/rows_{N}/shared_cache_results.json`.',
         f'Trace: {meta["accesses"]:,} accesses, {meta["unique_keys"]:,} unique (table, id) keys, '
         f'order: {meta["order"]}. Capacity = total vectors in the one shared cache.',
         'Hit rates are % of all accesses. Not comparable 1:1 with P3, where "256" meant 26 private '
         '256-entry caches.', '',
         '## Total hit rate, shared cache', '',
         '| capacity | ' + ' | '.join(SHORT[p] for p in ORDER) + ' |',
         '|---:|' + '---:|' * len(ORDER)]
    for c in CAPS:
        o.append(f'| {c:,} | ' + ' | '.join(pct(tot[p, c][0], sum(tot[p, c])) for p in ORDER) + ' |')

    o += ['', '## Five large tables (2, 11, 20, 15, 3)', '',
          'Large = >= 150,000 unique ids at both 2M and 10M (`results/P3/ANALYSIS.md`). '
          f'They make up {pct(large_acc, n_acc)}% of accesses ({large_acc:,} of {n_acc:,}).', '',
          'Share of all hits that come from the five large tables (%):', '',
          '| capacity | ' + ' | '.join(SHORT[p] for p in ORDER) + ' |',
          '|---:|' + '---:|' * len(ORDER)]
    for c in CAPS:
        o.append(f'| {c:,} | ' + ' | '.join(
            pct(sum(hits[p, c][t] for t in LARGE), tot[p, c][0]) for p in ORDER) + ' |')
    o += ['', 'Hit rate within the five large tables (their hits / their accesses, %):', '',
          '| capacity | ' + ' | '.join(SHORT[p] for p in ORDER) + ' |',
          '|---:|' + '---:|' * len(ORDER)]
    for c in CAPS:
        o.append(f'| {c:,} | ' + ' | '.join(
            pct(sum(hits[p, c][t] for t in LARGE), large_acc) for p in ORDER) + ' |')

    lh = tot[LRU, 256][0]
    verdicts = []
    for p in LFUS:
        h = tot[p, 256][0]
        verdicts.append(f'- {SHORT[p]}: {pct(h, n_acc)}% vs LRU {pct(lh, n_acc)}% '
                        f'({h - lh:+,} hits): ' + ('beats LRU.' if h > lh else
                                                   'does NOT beat LRU.' if h < lh else 'ties LRU.'))
    o += ['', '## Does LFU beat LRU in the shared cache at 256 vectors? (2M rows only)', ''] + verdicts
    other = [f'{c:,}: ' + ', '.join(f'{SHORT[p]} {"+" if tot[p, c][0] > tot[LRU, c][0] else "-"}'
                                    for p in LFUS) for c in CAPS if c != 256]
    o += ['', 'Sign of (LFU hits - LRU hits) at the other capacities: ' + '; '.join(other) + '.', '',
          '## Run', '',
          f'- Wall: parse {meta["wall_seconds"]["load"]:.1f} s, sweep {meta["wall_seconds"]["sweep"]:.1f} s '
          f'on {meta["workers"]} workers; whole job and peak memory in `results/P3b/rows_{N}/time.txt`.',
          '- The 20 part CSVs equal the JSON results, and per-table access counts equal '
          '`results/P3/rows_2000000/figs/zipf_per_table.csv` (checked before writing this file).', '']
    (root / 'RESULTS.md').write_text('\n'.join(o))


if __name__ == '__main__':
    main()
