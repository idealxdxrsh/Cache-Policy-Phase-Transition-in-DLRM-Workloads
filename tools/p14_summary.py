#!/usr/bin/env python3
"""Write results/P14/SUMMARY.md from files only.

Inputs: results/P14/<run>/<mode>_b<B>/{ncu.csv,run.json}, <run>/{env.txt,status.txt} for each run given,
results/P14/prep/check.json, results/P3b/RESULTS.md (2M total hit-rate table).
Per config, over the EmbeddingBag kernels of the profiled batches:
  L2 hit % (all ops)  = sum(lts__t_sectors_lookup_hit.sum) / sum(lts__t_sectors_lookup_hit.sum + _miss.sum)
  L2 read hit %       = same with lts__t_sectors_op_read_lookup_hit.sum and _miss.sum
  DRAM B / lookup     = sum(dram__bytes_read.sum) / profiled lookups (run.json)
  GPU us / batch      = sum(gpu__time_duration.sum) / profiled batches
  warps active %      = mean over kernels of sm__warps_active.avg.pct_of_peak_sustained_active
Usage: python3 -I tools/p14_summary.py results/P14/main1_<job> results/P14/main2_<job> results/P14/main3_<job>
"""
import csv
import glob
import json
import os
import re
import sys
from collections import Counter, defaultdict

P3B = 'results/P3b/RESULTS.md'


def read_ncu(path):
    with open(path) as f:
        lines = [ln for ln in f if ln.startswith('"')]
    rows = list(csv.DictReader(lines))
    k = defaultdict(dict)
    for r in rows:
        k[r['ID']]['name'] = r['Kernel Name']
        k[r['ID']][r['Metric Name']] = float(r['Metric Value'].replace(',', ''))
    return [k[i] for i in sorted(k, key=int)]


def p3b_table():
    """{capacity: {'LRU': x, 'LFU reset (LFURP)': y, ...}} from the 2M total hit-rate table."""
    with open(P3B) as f:
        txt = f.read()
    sec = txt.split('## Total hit rate, shared cache, 2M rows', 1)[1].split('\n## ', 1)[0]
    lines = [ln for ln in sec.splitlines() if ln.startswith('|')]
    head = [c.strip() for c in lines[0].strip('|').split('|')]
    out = {}
    for ln in lines[2:]:
        c = [x.strip() for x in ln.strip('|').split('|')]
        out[int(c[0].replace(',', ''))] = dict(zip(head[1:], c[1:]))
    return out


def main():
    runs = [r.rstrip('/') for r in sys.argv[1:]]
    jobs = [r.rsplit('_', 1)[1] for r in runs]
    cfgs = []
    for d in sorted(d for run in runs for d in glob.glob(os.path.join(run, '*_b*'))):
        if not os.path.exists(os.path.join(d, 'run.json')):
            continue
        with open(os.path.join(d, 'run.json')) as f:
            rj = json.load(f)
        ks = read_ncu(os.path.join(d, 'ncu.csv'))
        eb = [k for k in ks if 'EmbeddingBag' in k['name']]
        names = Counter(re.sub(r'\(.*', '', k['name']) for k in eb)
        h = sum(k['lts__t_sectors_lookup_hit.sum'] for k in eb)
        m = sum(k['lts__t_sectors_lookup_miss.sum'] for k in eb)
        rh = sum(k['lts__t_sectors_op_read_lookup_hit.sum'] for k in eb)
        rm = sum(k['lts__t_sectors_op_read_lookup_miss.sum'] for k in eb)
        cfgs.append(dict(
            mode=rj['mode'], B=rj['batch'], rows=rj['profiled_rows'], K=rj['profiled_batches'],
            lookups=rj['profiled_lookups_total'], exp=rj['expected_embedding_calls'],
            empty=rj['profiled_empty_table_batches'], n_all=len(ks), n_eb=len(eb), names=names,
            hit=100 * h / (h + m), rhit=100 * rh / (rh + rm), rsec=rh + rm,
            dram=sum(k['dram__bytes_read.sum'] for k in eb) / rj['profiled_lookups_total'],
            us=sum(k['gpu__time_duration.sum'] for k in eb) / 1e3 / rj['profiled_batches'],
            warps=sum(k['sm__warps_active.avg.pct_of_peak_sustained_active'] for k in eb) / len(eb),
            rj=rj))
    order = {'per_table': 0, 'concat': 1}
    cfgs.sort(key=lambda c: (c['B'], order[c['mode']]))
    rj0 = cfgs[0]['rj']
    with open('results/P14/prep/check.json') as f:
        chk = json.load(f)
    envs = []
    for run in runs:
        with open(os.path.join(run, 'env.txt')) as f:
            envs.append(f.read().splitlines())
    env = envs[0]
    same = all(e[0].split()[1] == env[0].split()[1] and e[2] == env[2] and e[3] == env[3] for e in envs)
    l2 = rj0['l2_cache_size_bytes']
    vb = rj0['dim'] * 4
    vec = l2 / vb
    p3 = p3b_table()
    cap = min(p3, key=lambda c: abs(c - vec))
    rel = ', '.join(f'`{os.path.relpath(r, "results/P14")}/`' for r in runs)
    L = []
    L.append('# P14: ncu on nn.EmbeddingBag, real Criteo stream (first 2M rows, 26 tables), one H100')
    L.append(f'Driver `cluster/p14_driver.sh`; jobs `jobs.txt`, `sacct.txt`; main jobs {", ".join(jobs)} ({rel}), '
             f'{env[0].split()[1]}, ncu {env[2].split(":", 1)[1].strip()}; same node, ncu and metrics in all: {same}. '
             f'Generated by `tools/p14_summary.py` from these files only.')
    L.append(f'- Stream (`prep/check.json`): parsed with the P3/P3b rule; every table equals the P3 dump: '
             f'{chk["all_tables_equal_p3_dump"]}; {chk["total_accesses"]:,} accesses, {chk["total_unique_table_id"]:,} '
             f'unique (table, id) = table rows (dense ids per table).')
    L.append(f'- Model (`tools/p14_profile.py`): EmbeddingBag(mode=sum), dim {rj0["dim"]} {rj0["dtype"]}, bag = one '
             f'(row, table), 0 or 1 lookup. per_table: 26 tables, 26 kernels per batch; concat: one table, one kernel, '
             f'26*B bags in (row, table) order.')
    L.append(f'- Warmup: rows [0, {rj0["warmup_rows"][1]:,}), not profiled. Profiled: {rj0["profiled_batches"]} '
             f'batches from row {rj0["profiled_rows"][0]:,} (rows per config below). ncu: application replay, '
             f'--cache-control none (no L2 flush), default --clock-control base.')
    L.append('')
    L.append('| B | layout | profiled rows | lookups | EmbBag kernels | L2 hit % (all) | L2 read hit % '
             '| L2 read sectors | DRAM B/lookup | GPU us/batch | warps active % |')
    L.append('|---:|---|---|---:|---:|---:|---:|---:|---:|---:|---:|')
    for c in cfgs:
        L.append(f'| {c["B"]:,} | {c["mode"]} | [{c["rows"][0]:,}, {c["rows"][1]:,}) | {c["lookups"]:,} | '
                 f'{c["n_eb"]} of {c["exp"]} | {c["hit"]:.4f} | {c["rhit"]:.4f} | {c["rsec"]:,.0f} | {c["dram"]:.2f} | '
                 f'{c["us"]:.3f} | {c["warps"]:.2f} |')
    L.append('')
    extra = sorted({n for c in cfgs for n in c['names']})
    other = [f'{c["mode"]} B={c["B"]}: {c["n_all"] - c["n_eb"]}' for c in cfgs if c['n_all'] != c['n_eb']]
    miss = [f'{c["mode"]} B={c["B"]}: {c["exp"] - c["n_eb"]} (empty table-batches {c["empty"]})'
            for c in cfgs if c['n_eb'] != c['exp']]
    kn = '; '.join('`%s`' % n for n in extra)
    L.append(f'- Kernel names: {kn}. Other kernels in the range: '
             f'{", ".join(other) if other else "none"}. Calls without a kernel: {", ".join(miss) if miss else "none"}.')
    L.append('- L2 hit % = lookup hit / (hit + miss) sectors (ncu `lts__t_sectors[_op_read]_lookup_{hit,miss}.sum`, '
             'names from `query_456792/`). Test job 454182 weighted `lts__t_sector_hit_rate.pct` by '
             '`lts__t_sectors.sum` (wrong denominator, gave 100.6 %); not used.')
    L.append('- First main jobs 456795-456797 failed before profiling (`sacct.txt`, `main*_45679?/status.txt`): files of '
             'the python env had been purged from /scratch; env rebuilt offline with the same 165 package builds '
             '(`env_rebuild/result_460012.txt`) before 460013-460015.')
    L.append(f'- A vector is {vb} B = {vb // 32} sectors of 32 B; DRAM B/lookup counts all DRAM reads of the kernels '
             f'(vectors, indices, offsets) divided by lookups.')
    L.append('')
    L.append('## Next to the P3b simulator (`results/P3b/RESULTS.md`, 2M rows, one shared cache, whole trace)')
    L.append(f'- H100 L2 = {l2:,} B (torch `L2_cache_size`, `run.json`); / {vb} B per vector = {vec:,.1f} vectors; '
             f'closest P3b capacity: {cap:,} (P3b has {", ".join(f"{x:,}" for x in sorted(p3))}).')
    row = p3[cap]
    gpu = ', '.join('%s B=%d %.4f' % (c['mode'], c['B'], c['rhit']) for c in cfgs)
    L.append(f'- P3b at {cap:,} vectors: LRU {row["LRU"]} %, LFU-reset (LFURP) {row["LFU reset (LFURP)"]} %. '
             f'GPU L2 read hit % above: {gpu}.')
    L.append('- The GPU L2 is not a pure LRU or LFU cache: it is a hardware cache with its own replacement policy, '
             'works on 32 B sectors and also holds indices, offsets and outputs. '
             'P3b counts hits per vector over the whole 2M-row trace from a cold cache; ncu counts sector hits '
             'over the profiled window only. The comparison is indicative, not a validation of either.')
    L.append('- Not measured: other GPUs (H200 counters blocked, `PREP.md`), other dims, pooling > 1, training, '
             'MLP kernels, nsys timelines.')
    out = 'results/P14/SUMMARY.md'
    with open(out, 'w') as f:
        f.write('\n'.join(L) + '\n')
    print(f'wrote {out}: {len(L)} lines')


if __name__ == '__main__':
    main()
