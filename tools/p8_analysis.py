"""Build results/P8/ANALYSIS.md from results/P8/power/, sim/, breakdown/ and bias/ files only.

Usage: python -I tools/p8_analysis.py [results/P8] [liberty file]
Sections: (1) mode 0 vs mode 1 per power component against the seed-to-seed spread (depth 64, seeds 1-3); (2) the
clock-pin recalculation and its cross-checks; (3) the per-component test of OpenSTA's state-probability weighting;
(4) the depth-256 and Criteo-slice runs. Energy per cycle = power x 2 ns (500 MHz); no merged totals.
"""
import json
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from p8_breakdown import ck_tables  # noqa: E402

LABEL = ('NanGate45, typical corner, pre-layout, no clock tree, flip-flop storage, random fill data, activity over '
         '10,000 cycles from {src}')
PJ = 2000.0
CLASSES = ('data', 'tag', 'counter', 'valid', 'control')


def groups(path):
    t = path.read_text()
    return {n: [float(x) for x in re.search(rf'^{n}\s+(\S+)\s+(\S+)\s+(\S+)\s+(\S+)', t, re.M).groups()]
            for n in ('Sequential', 'Combinational', 'Total')}


def comps(root, run):
    """Components of one run: name -> value (pJ per cycle, leakage in mW)."""
    b = json.loads((root / 'breakdown' / f'{run}.json').read_text())
    g = groups(root / 'power' / f'{run}.txt')
    c = b['clock_pin_model_W']
    return b, {'(a) CK fJ per flip-flop per cycle (recalculated)': c['ck_exact_state:all'] * 2e6 / b['flip_flops'],
               '(b) CK all flip-flops pJ (recalculated)': c['ck_exact_state:all'] * PJ,
               '(c) CK pJ, OpenSTA weighting (not used)': c['ck_opensta_model:all'] * PJ,
               '(d) flip-flop other internal pJ (OpenSTA)': (b['power_W']['ff:all']['internal'] -
                                                            c['ck_opensta_model:all']) * PJ,
               '(e) combinational internal pJ (OpenSTA)': g['Combinational'][0] * PJ,
               '(f) switching pJ (OpenSTA)': g['Total'][1] * PJ,
               '(g) leakage mW (OpenSTA)': g['Total'][2] * 1e3}


def main():
    root = Path(sys.argv[1] if len(sys.argv) > 1 else 'results/P8')
    lib = sys.argv[2] if len(sys.argv) > 2 else os.path.expanduser('~/eda/pdk/nangate45/NangateOpenCellLibrary_typical.lib')
    base = 'random_gl_w20000_n10000'
    o = ['# P8 analysis: mode 0 vs mode 1, the flip-flop clock-pin recalculation, and the state-probability bias', '',
         'Label of every power and energy number: "' + LABEL.format(src='<source named in the row>') + '" (depth-256 '
         'runs: 100,000 warm-up cycles, 10,000 recorded). Real embedding data is not random. 500 MHz netlists; depth '
         '256 meets 500 MHz only within noise (results/P5e/SUMMARY.md). Generated by `tools/p8_analysis.py` from '
         '`results/P8/power/`, `sim/`, `breakdown/` (`tools/p8_breakdown.py`) and `bias/` (`tools/p8_bias_check.py`).',
         '']
    # 1. modes vs seeds
    seeds = {m: [comps(root, f'd64_m{m}_{base}' + ('' if s == 1 else f'_s{s}')) for s in (1, 2, 3)] for m in (0, 1)}
    names = list(seeds[0][0][1])
    o += ['## 1. Depth 64, mode 0 vs mode 1, per component, against the seed-to-seed spread (random stimulus, seeds 1, '
          '2, 3)', '',
          'A mode difference is called real only if the smallest mode-0 minus mode-1 difference over the three seeds '
          'is larger than the largest within-mode spread (max - min over seeds).', '',
          '| component | mode 0, seeds 1/2/3 | mode 1, seeds 1/2/3 | mode 0 - mode 1, seeds 1/2/3 | largest '
          'within-mode spread | beyond the spread? |', '|---|---|---|---|---|---|']
    flags = {}
    for n in names:
        a = [x[1][n] for x in seeds[0]]
        b = [x[1][n] for x in seeds[1]]
        dd = [x - y for x, y in zip(a, b)]
        sp = max(max(a) - min(a), max(b) - min(b))
        beyond = min(abs(x) for x in dd) > sp and (all(x > 0 for x in dd) or all(x < 0 for x in dd))
        flags[n] = beyond
        o.append(f"| {n} | {' / '.join(f'{x:.4f}' for x in a)} | {' / '.join(f'{x:.4f}' for x in b)} | "
                 f"{' / '.join(f'{x:+.4f}' for x in dd)} | {sp:.4f} | {'yes' if beyond else 'no'} |")
    a1, b1 = seeds[0][0][0], seeds[1][0][0]
    ck_rows = [n for n in names if n.startswith(('(a)', '(b)'))]
    o += ['', "The mode gap in OpenSTA's dynamic energy reported earlier (commit 56a0aa6) sits in row (c), OpenSTA's "
          f"weighting of the clock-pin term (beyond the spread: {'yes' if flags[names[2]] else 'no'}). With the "
          "recalculated clock-pin energy (rows a, b) the modes "
          f"{'differ' if any(flags[n] for n in ck_rows) else 'do not differ'} beyond the seed spread. Why (c) "
          f"differs: mode 0 wrote the window's fills into "
          f"{a1['slots_with_q_change_in_window'].get('data_store', 0)} data_store slot(s), mode 1 into "
          f"{b1['slots_with_q_change_in_window'].get('data_store', 0)} (seed 1); data flip-flops with Q changed in the "
          f"window {a1['clock_pin_model_W']['flops_q_changed_in_window:data']} vs "
          f"{b1['clock_pin_model_W']['flops_q_changed_in_window:data']}, data Q toggles "
          f"{a1['toggles_in_window'].get('Q:data', 0)} vs {b1['toggles_in_window'].get('Q:data', 0)}. OpenSTA gives a "
          'flip-flop whose Q has duty p in the window about (p^2 + (1-p)^2) of the clock-pin energy, so spreading the '
          'same number of writes over more flip-flops lowers (c) without any change in real clock energy. Rows marked '
          '"yes" other than (c), if any, are measured differences beyond the seed spread for this stimulus and window '
          'only; each is weighed below against the bias the section-3 test measured for that component.', '']
    bias_files = sorted((root / 'bias').glob('*.json'))
    bpw = json.loads(bias_files[0].read_text())['power_W'] if bias_files else None
    for n in names:
        if not flags[n] or n.startswith('(c)'):
            continue
        a = [x[1][n] for x in seeds[0]]
        b = [x[1][n] for x in seeds[1]]
        rel = [abs(x - y) / x * 100 for x, y in zip(a, b)]
        line = (f'- {n}: mode 0 - mode 1 is {min(rel):.2f}-{max(rel):.2f}% of the mode-0 value. The two modes are '
                f'different netlists ({a1["cells"]:,} vs {b1["cells"]:,} cells, seed-1 breakdowns), so a component '
                'can differ through the synthesized logic as well as through activity.')
        if bpw and n.startswith('(e)'):
            bb = abs(bpw['comb_out_recomputed'] - bpw['comb_out_osta_debug']) / bpw['comb_out_osta_debug'] * 100
            comparable = bb >= 0.5 * min(rel)
            line += (f' The section-3 test (one other netlist and window) found OpenSTA\'s weighting moving this '
                     f'component by {bb:.2f}%, against a smallest mode difference of {min(rel):.2f}%; '
                     + ('these are comparable, so the mode difference in this component is not established beyond the '
                        'possible bias.' if comparable else 'the measured bias is under half of it.'))
        if bpw and n.startswith('(g)'):
            bb = max(abs(bpw['ff_leakage_recomputed'] - bpw['ff_leakage_osta']) / bpw['ff_leakage_osta'],
                     abs(bpw['comb_leakage_recomputed'] - bpw['comb_leakage_osta']) / bpw['comb_leakage_osta']) * 100
            line += (f' The section-3 test found OpenSTA\'s weighting moving leakage by at most {bb:.2f}%, '
                     + ('comparable to the mode difference, so it is not established beyond the possible bias.'
                        if bb >= 0.5 * min(rel) else 'under half of the mode difference. The difference is '
                        'consistent with the two netlists differing in cells; that cause was not tested separately.'))
        o.append(line)
    o.append('')
    # 2. clock-pin recalculation cross-checks
    ck = ck_tables(lib)
    o += ['## 2. Clock-pin recalculation and its cross-checks', '',
          'Per flip-flop and clock cycle, the CK-pin energy is rise + fall of the liberty CK internal_power table of the '
          'state the cell is in (`when` over D, Q, QN, RN), at clock slew 0 (ideal clock; linear extrapolation through '
          'the first two table points, as OpenSTA\'s Table1 lookup does). Recalculation: states weighted by the time '
          'each flip-flop spent in them in the window (QN = not Q, RN = 1). Energies per state, fJ:', '']
    for cell, rows in ck.items():
        o.append(f'- {cell}: ' + '; '.join(' & '.join(('' if pos else '!') + p for p, pos in l) + f' {e:.4f}'
                                          for l, e in rows))
    o += ['', '**Cross-check A, clock-only OpenSTA run** (`synthesis/p8/run_p8.sh clockonly`: all data pins activity 0, '
          'duty 0.5; CK 2 transitions per cycle; RN duty 1). The same tables with OpenSTA\'s independent weighting at '
          'those duties must give OpenSTA\'s Sequential internal power:', '',
          '| netlist | DFFR_X1 / DFF_X1 | OpenSTA clock-only Sequential internal W | tables, independent weighting W | '
          'relative difference |', '|---|---|---|---|---|']
    for d in (16, 64, 256):
        for m in (0, 1):
            pth = root / 'power' / f'd{d}_m{m}_clockonly.txt'
            if not pth.exists():
                continue
            net = Path(f'results/P5f_gls/netlists/d{d}_m{m}_500MHz/netlist.v').read_text()
            n = {c: len(re.findall(rf'^\s*{c}\s', net, re.M)) for c in ck}
            pred = sum(k * sum(e * 0.5 ** sum(1 for p, _ in l if p != 'RN') * (0 if ('RN', False) in l else 1)
                               for l, e in ck[c]) * 1e-15 * 5e8 for c, k in n.items())
            got = groups(pth)['Sequential'][0]
            o.append(f"| d{d} m{m} | {n['DFFR_X1']} / {n['DFF_X1']} | {got:.6e} | {pred:.6e} | "
                     f"{(pred - got) / got:+.1e} |")
    allruns = sorted(p.stem for p in (root / 'breakdown').glob('*.json'))
    errs = [(r, json.loads((root / 'breakdown' / f'{r}.json').read_text())['clock_pin_model_W']) for r in allruns]
    o += ['', f"**Cross-check B, OpenSTA per instance**: on every flip-flop with no D or Q toggle in the window, "
          f"OpenSTA's internal power is its CK-pin term alone; the tables with OpenSTA's weighting match it within "
          f"{max(e['check_untoggled_max_rel_err'] for _, e in errs):.1e} (relative) over "
          f"{sum(e['check_untoggled_flops'] for _, e in errs):,} flip-flop-windows in {len(errs)} runs.", '']
    bias = sorted((root / 'bias').glob('*.json'))
    if bias:
        bj = json.loads(bias[0].read_text())
        br = json.loads((root / 'breakdown' / f'{bias[0].stem}.json').read_text())['clock_pin_model_W']
        pw = bj['power_W']
        o += [f"**Cross-check C, per-event count** (`{bias[0].stem}`): counting each clock edge in the state after the "
              f"time step gives {pw['ff_ck_recomputed'] * 1e3:.4f} mW; the time-weighted recalculation gives "
              f"{br['ck_exact_state:all'] * 1e3:.4f} mW ({(br['ck_exact_state:all'] - pw['ff_ck_recomputed']) / pw['ff_ck_recomputed'] * 100:+.2f}%); "
              f"OpenSTA's weighting gives {pw['ff_ck_osta_debug'] * 1e3:.4f} mW (debug sum, 3 significant digits).", '']
    # 3. bias per component
    if bias:
        o += ['## 3. Does the state-probability weighting affect the other components? Test on one netlist', '',
              f"Run `{bias[0].stem}` (`results/P8/bias/{bias[0].name}`), window {bj['window_ps'][0]}-"
              f"{bj['window_ps'][1]} ps, {bj['cells']:,} cells, {bj['vcd_unmapped_pins']} unmapped pins. Method in "
              "`tools/p8_bias_check.py`: OpenSTA's own per-arc energies (debug log) are kept and only its probability "
              "weights are replaced by counts from the activity file. Simultaneous changes and `when` states are taken "
              "after the time step (zero delay).", '',
              '| component | OpenSTA mW | recomputed mW | difference | can the weighting affect it? |', '|---|---|---|---|---|']

        def r(name, a, b, verdict):
            o.append(f'| {name} | {a * 1e3:.5f} | {b * 1e3:.5f} | {(b - a) / a * 100:+.2f}% | {verdict} |')
        r('flip-flop CK pin', pw['ff_ck_osta_debug'], pw['ff_ck_recomputed'], 'yes (Q, QN independent); recalculated')
        r('flip-flop D pin', pw['ff_in_osta_debug'], pw['ff_in_recomputed'],
          'yes (CK state at the D change; zero-delay timing decides it); small next to the CK pin')
        r('flip-flop Q/QN outputs', pw['ff_out_osta_debug'], pw['ff_out_recomputed'],
          'only through the split between arcs; no material effect here')
        r('combinational internal (outputs)', pw['comb_out_osta_debug'], pw['comb_out_recomputed'],
          f"only through the split between arcs; {bj['output_toggles_without_input_change_same_step']} output "
          'toggles had no input change in the same step and kept OpenSTA\'s weights')
        r('combinational switching', pw['comb_sw_osta_debug'], pw['comb_sw_osta_debug'],
          f"no: 0.5 C V^2 x toggle rate; OpenSTA's toggle rate equals the activity file's within "
          f"{bj['switching_density_vs_vcd_max_rel_dev'] * 100:.2f}% (3-digit rounding) on all "
          f"{bj['switching_density_vs_vcd_pins']} output pins")
        r('flip-flop leakage', pw['ff_leakage_osta'], pw['ff_leakage_recomputed'],
          'yes in principle (state-weighted); negligible here')
        r('combinational leakage', pw['comb_leakage_osta'], pw['comb_leakage_recomputed'],
          'yes in principle (input states taken as independent); negligible here')
        o += ['', 'Combinational input pins have no internal-power groups in this netlist\'s cells (none in the debug '
              'log). The test covers one netlist and one window; other windows were not tested.', '']
    # 4. depth 256 and slices
    o += ['## 4. Depth-256 and Criteo-slice runs', '',
          'One run per configuration (no seed repeats on these), so no mode-difference claim is made for them. '
          'Slots rewritten in the window and OpenSTA\'s clock-pin bias per run:', '',
          '| run | data_store / tag_store slots with Q changed | data flip-flops with Q changed | CK pJ recalculated | '
          'CK pJ OpenSTA weighting | OpenSTA low by |', '|---|---|---|---|---|---|']
    for run in allruns:
        if run.startswith('d64_') and run.endswith(('_s2', '_s3')):
            continue
        b, c = comps(root, run)
        s = b['slots_with_q_change_in_window']
        ex, os_ = c['(b) CK all flip-flops pJ (recalculated)'], c['(c) CK pJ, OpenSTA weighting (not used)']
        o.append(f"| {run} | {s.get('data_store', 0)} / {s.get('tag_store', 0)} | "
                 f"{b['clock_pin_model_W']['flops_q_changed_in_window:data']} | {ex:.3f} | {os_:.3f} | "
                 f"{(ex - os_) / ex * 100:.1f}% |")
    (root / 'ANALYSIS.md').write_text('\n'.join(o) + '\n')
    print(f'wrote {root / "ANALYSIS.md"}')


if __name__ == '__main__':
    main()
