"""Build results/P8/ANALYSIS.md from results/P8/power/<run>.txt (OpenSTA report_power), results/P8/sim/<run>.txt and
results/P8/breakdown/<run>.json (tools/p8_breakdown.py) only.

Usage: python -I tools/p8_analysis.py [results/P8]
Energy per cycle = power x 2 ns (500 MHz); 1 mW -> 2 pJ per cycle.
"""
import json
import re
import sys
from pathlib import Path

LABEL = ('NanGate45, typical corner, pre-layout, no clock tree, no extracted parasitics, flip-flop storage, activity '
         'from zero-delay gate-level simulation (VCD of the recorded window) over 10,000 cycles')
CLASSES = ('data', 'tag', 'counter', 'valid', 'control')
PJ = 2000.0     # W -> pJ per 2 ns cycle


def groups(path):
    t = path.read_text()
    g = {}
    for name in ('Sequential', 'Combinational', 'Total'):
        g[name] = [float(x) for x in re.search(rf'^{name}\s+(\S+)\s+(\S+)\s+(\S+)\s+(\S+)', t, re.M).groups()]
    return g


def hits(path):
    line = next(l for l in path.read_text().splitlines() if l.startswith('p8_power'))
    kv = dict(re.findall(r'(\w+)=(-?\d+)', line))
    return int(kv['win_hits']), int(kv['win_responses'])


def load(root, run):
    b = json.loads((root / 'breakdown' / f'{run}.json').read_text())
    g = groups(root / 'power' / f'{run}.txt')
    p, c = b['power_W'], b['clock_pin_model_W']
    dyn = (g['Total'][0] + g['Total'][1]) * PJ
    r = {'run': run, 'g': g, 'b': b, 'dyn': dyn, 'hits': hits(root / 'sim' / f'{run}.txt'),
         'ck_osta': c['ck_opensta_model:all'] * PJ, 'ck_exact': c['ck_exact_state:all'] * PJ,
         'ff_int': p['ff:all']['internal'] * PJ}
    r['dyn_exact'] = dyn - r['ck_osta'] + r['ck_exact']
    return r


def f3(x):
    return f'{x:.3f}'


def main():
    root = Path(sys.argv[1] if len(sys.argv) > 1 else 'results/P8')
    base = 'random_gl_w20000_n10000'
    seeds = {m: [load(root, f'd64_m{m}_{base}' + ('' if s == 1 else f'_s{s}')) for s in (1, 2, 3)] for m in (0, 1)}
    four = [load(root, f'd{d}_m{m}_{base}') for d in (16, 64) for m in (0, 1)]
    o = ['# P8 analysis: depth-64 mode 0 vs mode 1 dynamic energy, and the flip-flop share of dynamic energy', '',
         f'Label for every power and energy number below unless marked otherwise: {LABEL}. Random stimulus '
         '(P5f generator), random fill data; real embedding data is not random. 500 MHz netlists; dynamic energy per '
         'cycle = (internal + switching power) x 2 ns. Generated by `tools/p8_analysis.py` from `results/P8/power/`, '
         '`results/P8/sim/` and `results/P8/breakdown/` (`tools/p8_breakdown.py`).', '']
    # 1. seed spread
    o += ['## 1. Seed-to-seed spread (depth 64, seeds 1, 2, 3; seed sets the request stream and the fill data)', '',
          '| mode | seed 1 pJ | seed 2 pJ | seed 3 pJ | min-max spread pJ | window hits / responses (seeds 1, 2, 3) |',
          '|---|---|---|---|---|---|']
    for m in (0, 1):
        d = [r['dyn'] for r in seeds[m]]
        o.append(f'| {m} | ' + ' | '.join(f3(x) for x in d) + f' | {f3(max(d) - min(d))} | ' +
                 ', '.join(f'{h}/{n}' for h, n in (r['hits'] for r in seeds[m])) + ' |')
    gap = [a['dyn'] - b['dyn'] for a, b in zip(seeds[0], seeds[1])]
    spread = max(max(r['dyn'] for r in seeds[m]) - min(r['dyn'] for r in seeds[m]) for m in (0, 1))
    o += ['', f'Mode 0 minus mode 1, same seed: {", ".join(f3(x) for x in gap)} pJ per cycle. The largest '
          f'seed-to-seed spread within one mode is {f3(spread)} pJ. **The difference is not within the seed-to-seed '
          'spread.**', '']
    # 2. breakdown by group and class
    a, b = seeds[0][0], seeds[1][0]
    o += ['## 2. Breakdown, depth 64, seed 1 (pJ per cycle; OpenSTA per-instance power summed by class)', '',
          'Register classes by the register a flip-flop drives: data = data_store, tag = tag_store, counter = '
          'freq_cnt, valid = valid_bits, control = everything else (state, req_addr_reg, req_addr_grp, stageA_min, '
          'victim_reg and the output registers resp_valid, resp_data, hit_flag, fill_req, fill_addr). A combinational '
          'cell is in a class if every flip-flop D input it feeds is in that class, otherwise "shared" ("none": feeds no '
          'D input). Per-class sums equal the OpenSTA group totals.', '',
          '| part | mode 0 | mode 1 | mode 0 - mode 1 |', '|---|---|---|---|']

    def row(name, x, y):
        o.append(f'| {name} | {f3(x)} | {f3(y)} | {f3(x - y)} |')
    for gi, gname in ((0, 'internal'), (1, 'switching')):
        for grp in ('Sequential', 'Combinational'):
            row(f'{grp} {gname} (group)', a['g'][grp][gi] * PJ, b['g'][grp][gi] * PJ)
    row('**total dynamic**', a['dyn'], b['dyn'])
    for k in CLASSES:
        pa, pb = a['b']['power_W'][f'ff:{k}'], b['b']['power_W'][f'ff:{k}']
        row(f'flip-flops {k} ({pa["cells"]}): internal + switching', (pa['internal'] + pa['switching']) * PJ,
            (pb['internal'] + pb['switching']) * PJ)
    for k in CLASSES + ('shared', 'none'):
        pa, pb = a['b']['power_W'].get(f'comb:{k}'), b['b']['power_W'].get(f'comb:{k}')
        if pa and pb:
            row(f'combinational cells in the {k} cone: internal + switching',
                (pa['internal'] + pa['switching']) * PJ, (pb['internal'] + pb['switching']) * PJ)
    # 3. mechanism
    o += ['', '## 3. Why: the flip-flops\' clock-pin internal power in OpenSTA depends on how many slots are rewritten',
          '',
          'The DFFR_X1 CK-pin internal-power tables are indexed by `when` states over D, Q, QN and RN; the per-cycle '
          'energy is 6.824-7.432 fJ in every RN = 1 state (rise + fall at clock slew 0; liberty file, extracted by '
          '`tools/p8_breakdown.py` ck_tables). OpenSTA weights each state by '
          'the product of the pins\' own duties (`evalBddDuty`, power/Power.cc), treating Q and QN as independent. A '
          'flip-flop that holds its value for the whole window gets the full energy; one whose Q has duty p in the '
          'window gets about (p^2 + (1-p)^2) of it, so one write in mid-window halves it, although the clock-pin '
          'energy of the real cell does not depend on that. The model below reproduces OpenSTA: on every flip-flop '
          'with no D or Q toggle in the window, the difference from OpenSTA\'s per-instance internal power is at most '
          f'{max(r["b"]["clock_pin_model_W"]["check_untoggled_max_rel_err"] for r in four):.1e} (relative); with all '
          'data activity 0 it gives the clock-only OpenSTA result (`results/P8/power/d16_m*_clockonly.txt`).', '',
          '"Exact state" weights each state by the fraction of the window the flip-flop actually spent in that (D, Q) '
          'state (QN = not Q, RN = 1); it is recomputed by `tools/p8_breakdown.py` from the liberty tables and the '
          'VCD, not an OpenSTA output.', '',
          '| depth 64, seed 1 | mode 0 | mode 1 |', '|---|---|---|']
    for k in ('data', 'tag', 'counter'):
        reg = {'data': 'data_store', 'tag': 'tag_store', 'counter': 'freq_cnt'}[k]
        o.append(f'| {reg} slots with any Q bit changed in the window | '
                 f'{a["b"]["slots_with_q_change_in_window"].get(reg, 0)} | '
                 f'{b["b"]["slots_with_q_change_in_window"].get(reg, 0)} |')
    for k in CLASSES:
        ca, cb = a['b']['clock_pin_model_W'], b['b']['clock_pin_model_W']
        ta, tb = a['b']['toggles_in_window'], b['b']['toggles_in_window']
        o.append(f'| {k}: flip-flops with Q changed / Q toggles in the window | '
                 f'{ca[f"flops_q_changed_in_window:{k}"]} / {ta.get(f"Q:{k}", 0)} | '
                 f'{cb[f"flops_q_changed_in_window:{k}"]} / {tb.get(f"Q:{k}", 0)} |')
    for k in CLASSES + ('all',):
        ca, cb = a['b']['clock_pin_model_W'], b['b']['clock_pin_model_W']
        o.append(f'| {k}: CK-pin internal pJ, OpenSTA model / exact state | '
                 f'{f3(ca[f"ck_opensta_model:{k}"] * PJ)} / {f3(ca[f"ck_exact_state:{k}"] * PJ)} | '
                 f'{f3(cb[f"ck_opensta_model:{k}"] * PJ)} / {f3(cb[f"ck_exact_state:{k}"] * PJ)} |')
    o += ['', '| run | dynamic pJ (OpenSTA) | CK-pin pJ, OpenSTA model | CK-pin pJ, exact state | dynamic pJ with '
          'exact-state CK (recomputed) |', '|---|---|---|---|---|']
    for m in (0, 1):
        for r in seeds[m]:
            o.append(f'| {r["run"]} | {f3(r["dyn"])} | {f3(r["ck_osta"])} | {f3(r["ck_exact"])} | '
                     f'{f3(r["dyn_exact"])} |')
    ex = [x['dyn_exact'] - y['dyn_exact'] for x, y in zip(seeds[0], seeds[1])]
    ck_gap = a['ck_osta'] - b['ck_osta']
    o += ['', f'Findings: of the seed-1 gap of {f3(a["dyn"] - b["dyn"])} pJ, {f3(ck_gap)} pJ is the CK-pin internal '
          'term of the OpenSTA model. The two modes toggle about the same number of data bits in the window, but mode 0 '
          f'writes the fills in the window into {a["b"]["slots_with_q_change_in_window"].get("data_store", 0)} data_store '
          f'slot(s) and mode 1 into {b["b"]["slots_with_q_change_in_window"].get("data_store", 0)}, so far more '
          'flip-flops in mode 1 change state once or a few times and lose part of their clock-pin energy in the '
          'OpenSTA model. With exact-state weighting the CK-pin energy of the two modes is equal to within '
          f'{f3(abs(a["ck_exact"] - b["ck_exact"]))} pJ, and mode 0 minus mode 1 becomes {", ".join(f3(x) for x in ex)} '
          f'pJ (seeds 1, 2, 3). **The {a["dyn"]:.2f} vs {b["dyn"]:.2f} pJ difference is explained, and it is an artifact of '
          'the OpenSTA '
          'state-probability model combined with how many slots the window rewrites, not a difference in switching '
          'activity or in real clock energy; it should not be reported as a mode-0 vs mode-1 energy difference.** '
          'The same model also lowers every vector-based Sequential internal figure in `results/P8/RESULTS.md` by an '
          'amount that depends on the window (column "CK-pin pJ" OpenSTA model vs exact state).', '']
    # 4. shares
    o += ['## 4. Share of dynamic energy: flip-flop clock-pin and other internal power vs switching (seed 1)', '',
          'CK-pin internal = OpenSTA-model value from section 3; other flip-flop internal = flip-flop internal power '
          'minus that (D- and Q-pin internal energy). Percentages of the OpenSTA dynamic energy. Last column: the '
          'CK-pin share if the exact-state CK-pin energy replaces the OpenSTA-model one (recomputed).', '',
          '| run | dynamic pJ | flip-flop CK-pin internal | flip-flop other internal | combinational internal | '
          'switching (all cells) | CK-pin share, exact state |', '|---|---|---|---|---|---|---|']
    for r in four:
        g = r['g']
        sw = (g['Total'][1]) * PJ
        comb_int = g['Combinational'][0] * PJ
        other = r['ff_int'] - r['ck_osta']

        def pc(x, tot=r['dyn']):
            return f'{f3(x)} ({x / tot * 100:.1f}%)'
        o.append(f'| {r["run"]} | {f3(r["dyn"])} | {pc(r["ck_osta"])} | {pc(other)} | {pc(comb_int)} | {pc(sw)} | '
                 f'{r["ck_exact"] / r["dyn_exact"] * 100:.1f}% of {f3(r["dyn_exact"])} |')
    o += ['', 'Caveats: zero-delay simulation (no glitches), ideal clock (no clock-tree cells: the clock-tree power of '
          'a real layout is not included), activity of one 10,000-cycle window after 20,000 warm-up cycles.']
    (root / 'ANALYSIS.md').write_text('\n'.join(o) + '\n')
    print(f'wrote {root / "ANALYSIS.md"}')


if __name__ == '__main__':
    main()
