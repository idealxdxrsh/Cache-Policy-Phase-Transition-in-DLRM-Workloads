"""Build results/P3/ANALYSIS.md from the P3 result CSVs (no other inputs).

Usage: python -I tools/p3_analysis.py results/P3
Reads rows_<N>/figs/hit_rates.csv and rows_<N>/figs/zipf_per_table.csv.
"Large" tables: unique ids >= UNIQUE_MIN at BOTH row counts.
"""
import csv
import sys
from pathlib import Path

ROWS = (2000000, 10000000)
UNIQUE_MIN = 150000
CAPS = (64, 256, 1000, 10000)
LRU = 'LRU'
LFUS = ('LFU (persistent counters)', 'LFU (gem5 LFURP — reset on eviction)')
SHOW = (LRU, *LFUS, 'ARC', 'W-TinyLFU (Count-Min, window=1%)', 'Belady (MIN, offline)')
SHORT = {LRU: 'LRU', LFUS[0]: 'LFU persist', LFUS[1]: 'LFU reset (LFURP)', 'ARC': 'ARC',
         'W-TinyLFU (Count-Min, window=1%)': 'W-TinyLFU', 'Belady (MIN, offline)': 'Belady'}


def load(root, n):
    d = root / f'rows_{n}' / 'figs'
    hm = {}
    with open(d / 'hit_rates.csv', newline='') as f:
        for r in csv.DictReader(f):
            hm[r['policy'], int(r['capacity']), r['table']] = (int(r['hits']), int(r['misses']))
    with open(d / 'zipf_per_table.csv', newline='') as f:
        uniq = {r['table']: int(r['unique']) for r in csv.DictReader(f)}
    return hm, uniq


def pct(h, m):
    return f'{h / (h + m) * 100:.4f}'


def group(hm, p, c, tables):
    return (sum(hm[p, c, t][0] for t in tables), sum(hm[p, c, t][1] for t in tables))


def main():
    root = Path(sys.argv[1])
    data = {n: load(root, n) for n in ROWS}
    large = [t for t in data[ROWS[0]][1]
             if all(data[n][1][t] >= UNIQUE_MIN for n in ROWS)]
    large.sort(key=lambda t: -data[ROWS[-1]][1][t])
    caps_all = sorted({c for (_, c, _) in data[ROWS[0]][0]})
    o = ['# P3 analysis: large tables, cache organisation, LRU vs LFU',
         '',
         'Generated by `tools/p3_analysis.py` from `results/P3/rows_{2000000,10000000}/figs/'
         'hit_rates.csv` and `.../zipf_per_table.csv` only. Hit rates are % of accesses.',
         'Group rates ("large, combined") are sum(hits)/sum(hits+misses) over the listed '
         'tables, computed here from the CSV hit and miss counts.',
         '',
         '## 1. Large-cardinality tables',
         '',
         f'Threshold: unique ids >= {UNIQUE_MIN:,} at both 2M and 10M rows '
         '(`zipf_per_table.csv`, column `unique`). Tables chosen this way are the same at both sizes.',
         '',
         '| table | unique, 2M | unique, 10M |', '|---:|---:|---:|']
    o += [f'| {t} | {data[ROWS[0]][1][t]:,} | {data[ROWS[1]][1][t]:,} |' for t in large]
    rest = sorted((t for t in data[ROWS[0]][1] if t not in large),
                  key=lambda t: -data[ROWS[1]][1][t])[0]
    o += ['', f'Next largest (excluded): table {rest}, {data[ROWS[0]][1][rest]:,} unique at 2M, '
          f'{data[ROWS[1]][1][rest]:,} at 10M.', '']
    for n in ROWS:
        hm = data[n][0]
        o += [f'### {n:,} rows', '',
              '| capacity | table | ' + ' | '.join(SHORT[p] for p in SHOW) + ' |',
              '|---:|---|' + '---:|' * len(SHOW)]
        for c in CAPS:
            for t in large:
                o.append(f'| {c:,} | {t} | ' + ' | '.join(pct(*hm[p, c, t]) for p in SHOW) + ' |')
            o.append(f'| {c:,} | **large, combined** | '
                     + ' | '.join(pct(*group(hm, p, c, large)) for p in SHOW) + ' |')
        o.append('')

    o += ['## 2. Cache organisation in the simulator', '',
          '- One cache per table. `trace_sim/run_trace_sim.py` `run_sweep` builds one job per '
          '(policy, capacity, table) and `run_one` creates a fresh cache for each, replaying only '
          'that table\'s trace. Results record `capacity_unit: "vectors, one cache per table"`.',
          '- So "256 vectors" means 26 separate 256-entry caches (at most 6,656 entries in total; '
          'tables with fewer than 256 unique ids never fill theirs), not one 256-entry cache.',
          '- The "all" rows in `hit_rates.csv` are sums of hits and misses over the 26 '
          'independent caches (`aggregate`), not a shared-cache simulation.',
          '',
          'A single shared 256-entry cache would require:',
          '- One interleaved trace in request order. The loader reads Criteo row by row, but '
          'splits ids into 26 per-table lists, and skips empty fields, so the dumped '
          '`table_XX.u32` files no longer line up by row; they cannot be re-interleaved. '
          'It needs a new trace (e.g. per row, C1..C26 in column order, with row index kept).',
          '- Keys that include the table, e.g. (table, id): ids are per-column hashes and the '
          'same value can appear in two columns but refers to different embedding rows.',
          '- One cache instance per (policy, capacity) over all tables. This removes the '
          'per-table array parallelism: one job replays all accesses '
          '(46,128,690 at 2M, 231,492,097 at 10M, `dump_log.txt`). Belady\'s `prepare` would '
          'need next-use positions over the whole interleaved trace.',
          '- The interleaving order is a modelling choice (row order, batch order) and should be stated.',
          '',
          'Current code: not supported. There is no shared-cache mode or table-qualified key, '
          'and the dump format drops row alignment.',
          '',
          '## 3. Does LRU beat LFU at any capacity?', '',
          f'Checked every capacity {caps_all[0]:,}..{caps_all[-1]:,} ({len(caps_all)} values) by '
          'comparing hit counts exactly.', '']
    for n in ROWS:
        hm = data[n][0]
        for label, tabs in (('combined (all 26 tables)', None), ('large, combined', large)):
            for p in LFUS:
                lose = [c for c in caps_all
                        if (hm[LRU, c, 'all'][0] if tabs is None else group(hm, LRU, c, tabs)[0])
                        > (hm[p, c, 'all'][0] if tabs is None else group(hm, p, c, tabs)[0])]
                verdict = ('LRU beats it at ' + ', '.join(f'{c:,}' for c in lose)) if lose \
                    else 'LRU never beats it'
                o.append(f'- {n:,} rows, {label}, {SHORT[p]}: {verdict}.')
        for p in LFUS:
            per = [f'{t}@{c:,}' for t in large for c in caps_all if hm[LRU, c, t][0] > hm[p, c, t][0]]
            o.append(f'- {n:,} rows, individual large tables, {SHORT[p]}: '
                     + ('LRU wins at ' + ', '.join(per) if per else 'LRU never wins') + '.')
        o.append('')
    o.append('LRU does beat LFU on some individual small tables: at 256 vectors, 10M rows, '
             'persistent LFU loses on tables 1, 4, 10, 12, 14, 17 (see `SUMMARY.md`); none of '
             'these is in the large set.')
    o.append('')
    (root / 'ANALYSIS.md').write_text('\n'.join(o))


if __name__ == '__main__':
    main()
