"""P5f: wrap a gate-level netlist so the unmodified rtl/v2/tb_lfu_cache.sv can drive it.

Usage: python -I tools/p5f_wrap.py <netlist.v> <depth> <mode> <out_dir>
Writes <out_dir>/netlist_gl.v (the netlist with its module renamed lfu_cache_controller_gl, nothing else changed)
and <out_dir>/wrapper.v: a module lfu_cache_controller with the testbench's parameters that stops with $fatal
unless they equal the netlist's (depth, mode, 20/128/6), instantiates the netlist, and rebuilds the three arrays
the testbench reads by hierarchical reference (valid_bits, tag_store, freq_cnt; tb lines 108-109) from the
netlist's register nets \\valid_bits[k], \\tag_store[k], \\freq_cnt[k]. Functional only, zero delay.
"""
import re
import sys
from pathlib import Path

PORTS = 'clk, rst_n, req_valid, req_addr, resp_valid, resp_data, hit_flag, fill_req, fill_addr, fill_valid, fill_data'


def main():
    net, d, m, out = Path(sys.argv[1]), int(sys.argv[2]), int(sys.argv[3]), Path(sys.argv[4])
    text = net.read_text()
    text, n = re.subn(r'^module lfu_cache_controller\(', 'module lfu_cache_controller_gl(', text, flags=re.M)
    assert n == 1, 'netlist module header not found'
    out.mkdir(parents=True, exist_ok=True)
    (out / 'netlist_gl.v').write_text(text)
    for name in ('valid_bits', 'tag_store', 'freq_cnt'):
        for k in range(d):
            assert re.search(r'^\s+wire (\[\d+:0\] )?\\' + re.escape(f'{name}[{k}]') + ' ;', text, re.M), f'{name}[{k}] missing'
    w = [f'// Generated by tools/p5f_wrap.py for {net} (depth {d}, mode {m}). Functional only, zero delay.',
         'module lfu_cache_controller #(parameter CACHE_DEPTH = 256, parameter ADDR_WIDTH = 20, parameter VECTOR_WIDTH = 128,',
         '    parameter COUNTER_WIDTH = 6, parameter COUNTER_MODE = 0, parameter GROUPS = 16) (',
         '    input wire clk, input wire rst_n, input wire req_valid, input wire [19:0] req_addr,',
         '    output wire resp_valid, output wire [127:0] resp_data, output wire hit_flag,',
         '    output wire fill_req, output wire [19:0] fill_addr, input wire fill_valid, input wire [127:0] fill_data);',
         f'initial if (CACHE_DEPTH != {d} || COUNTER_MODE != {m} || ADDR_WIDTH != 20 || VECTOR_WIDTH != 128',
         '            || COUNTER_WIDTH != 6 || GROUPS != 16)',
         f'    $fatal(1, "wrapper built for depth {d} mode {m}, got depth %0d mode %0d", CACHE_DEPTH, COUNTER_MODE);',
         f'lfu_cache_controller_gl gl({", ".join(f".{p}({p})" for p in PORTS.split(", "))});',
         f'wire        valid_bits [0:{d - 1}];', f'wire [19:0] tag_store  [0:{d - 1}];', f'wire [5:0]  freq_cnt   [0:{d - 1}];']
    for k in range(d):
        w.append(f'assign valid_bits[{k}] = gl.\\valid_bits[{k}] ; assign tag_store[{k}] = gl.\\tag_store[{k}] ; '
                 f'assign freq_cnt[{k}] = gl.\\freq_cnt[{k}] ;')
    w.append('endmodule')
    (out / 'wrapper.v').write_text('\n'.join(w) + '\n')


if __name__ == '__main__':
    main()
