"""Fig.: H100 L2 read hit rate of the nn.EmbeddingBag kernels vs batch size, per-table and concatenated layouts.

Reads the table of results/P14/SUMMARY.md (generated by tools/p14_summary.py from the ncu files of jobs
460013-460015): column 'L2 read hit %' = lts__t_sectors_op_read_lookup_hit / (hit + miss), per batch size and layout.
"""
from style import SINGLE, plt, read, save

hdr, data = None, {}
for ln in read('results/P14/SUMMARY.md').splitlines():
    if not ln.startswith('|'):
        continue
    cells = [c.strip() for c in ln.strip('|').split('|')]
    if cells[0] == 'B':
        hdr = cells
    elif hdr and cells[0].replace(',', '').isdigit():
        r = dict(zip(hdr, cells))
        data.setdefault(r['layout'], []).append((int(r['B'].replace(',', '')), float(r['L2 read hit %'])))
if sorted(data) != ['concat', 'per_table'] or any(len(v) != 3 for v in data.values()):
    raise SystemExit(f'unexpected P14 table: {data}')

fig, ax = plt.subplots(figsize=(SINGLE, 1.55))
style = {'per_table': ('26 tables, one kernel per table', '#0072B2', 's', '-'),
         'concat': ('one concatenated table, one kernel', '#D55E00', 'o', '--')}
for lay, (lab, col, mk, ls) in style.items():
    xs, ys = zip(*sorted(data[lay]))
    ax.plot(xs, ys, color=col, marker=mk, ls=ls, label=lab)
ax.set_xscale('log', base=2)
ax.set_xticks([64, 1024, 16384], ['64', '1,024', '16,384'])
ax.minorticks_off()
ax.set_xlabel('Batch size (rows of the Criteo stream)')
ax.set_ylabel('L2 read hit rate (%)')
ax.set_ylim(50, 80)
ax.legend(loc='lower left')
save(fig, 'fig_l2')
