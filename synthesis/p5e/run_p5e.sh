#!/bin/bash
# P5e driver, local only (no cluster). NanGate45, not TSMC. Pre-layout. No power step. No RTL change.
# Measurement flow only: old flow = synthesis/p5/synth.ys.in (abc -liberty -D <period> -constr, Yosys's
# built-in script, no wire loads inside ABC); new flow = synthesis/p5e/synth_td.ys.in + abc_td.script.in
# (delay-oriented restructuring, &nf -D, buffering incl. flip-flop outputs, upsize/dnsize, all with the
# liberty default wire load 5K_hvratio_1_1 that OpenSTA also uses, and an ABC target of period - 141.5 ps).
# 141.5 ps = clk->Q 0.0983 + setup 0.0432 ns on the worst path of results/P5d/d16_m0_1000MHz/sta.txt, the
# largest clk->Q + setup sum on the six P5d 1 GHz worst paths: ABC sees flip-flop outputs as inputs and
# flip-flop inputs as outputs, so it does not see these two delays.
# Steps:
#   synth   new flow on rtl-v2-final, depths 16/64/256 x modes 0/1 x 1 GHz/500 MHz       -> results/P5e/new/
#   noise   new flow, 1 GHz, the same 7 other same-logic designs as results/P5d/NOISE.md -> results/P5e/noise/
#   mcp     OpenSTA again on the old (results/P5d) and new 1 GHz/500 MHz netlists with the multicycle
#           exceptions of tools/p5e_mcp.py (synthesis/p5e/sta_mcp.tcl)                   -> results/P5e/mcp/
#   report  tables                                                                       -> results/P5e/*.md
#   bash synthesis/p5e/run_p5e.sh [synth|noise|mcp|report]...   default: all four
set -euo pipefail
ROOT=$(cd "$(dirname "$0")/../.." && pwd)
R=$ROOT/results/P5e
LIB=${LIB:-$HOME/eda/pdk/nangate45/NangateOpenCellLibrary_typical.lib}
STEPS=${*:-"synth noise mcp report"}
JOBS=${JOBS:-8}
export YS_IN=$ROOT/synthesis/p5e/synth_td.ys.in ABC_IN=$ROOT/synthesis/p5e/abc_td.script.in ABC_BUDGET_PS=141.5
git -C "$ROOT" diff --quiet rtl-v2-final -- rtl/v2/lfu_cache_controller.v || { echo "rtl/v2 differs from rtl-v2-final"; exit 1; }
NULLS="null_tagcmp_swap null_hitor_swap null_stageB_gt"
P5D=$ROOT/results/P5d
# one job per line: <outdir relative to ROOT> <rtl> <depth> <mode> <MHz>; depth 256 first (longest)
jobs() {
    for d in 256 64 16; do for m in 0 1; do case $1 in
    synth) for f in 1000 500; do echo "results/P5e/new $ROOT/rtl/v2/lfu_cache_controller.v $d $m $f"; done ;;
    noise)
        for v in $NULLS; do echo "results/P5e/noise/final_$v $P5D/noise/rtl/$v.v $d $m 1000"; done
        echo "results/P5e/noise/packed $P5D/attempt1_packed_vectors/lfu_cache_controller_packed.v $d $m 1000"
        for v in $NULLS; do echo "results/P5e/noise/packed_$v $P5D/attempt1_packed_vectors/noise/rtl/$v.v $d $m 1000"; done ;;
    esac; done; done
}
run1() {  # outdir rtl depth mode MHz
    OUTDIR=$1 RTL=$2 MODES=$4 FREQS=$5 bash "$ROOT/synthesis/p5/run_p5.sh" "$3"
}
export -f run1; export ROOT
for step in $STEPS; do case $step in
synth|noise)
    mkdir -p "$R"
    rc=0; jobs "$step" | xargs -P "$JOBS" -L 1 bash -c 'run1 "$@"' _ > "$R/run_$step.txt" 2>&1 || rc=1
    dirs=$( [ "$step" = synth ] && echo "$R/new" || echo "$R/noise/*" )
    for dd in $dirs; do
        gzip -f "$dd"/d*/yosys.log 2>/dev/null || true
        (cd "$dd" && sha256sum d*/netlist.v > netlists.sha256)
    done
    sort -o "$R/run_$step.txt" "$R/run_$step.txt"
    [ $rc = 0 ] || exit 1 ;;
mcp)
    for flow in old new; do
        src=$( [ $flow = old ] && echo "$P5D" || echo "$R/new" )
        for run in "$src"/d*_*MHz; do
            o=$R/mcp/$flow/$(basename "$run"); mkdir -p "$o"
            python3 -I "$ROOT/tools/p5e_mcp.py" "$run/netlist.v" "$o/mcp.tcl"
            LIB=$LIB OUT=$run MCP=$o/mcp.tcl PERIOD_NS=$(grep -m1 '^PERIOD_NS' "$run/sta.txt" | cut -d' ' -f2) \
                "$HOME/eda/bin/sta" -no_init -exit "$ROOT/synthesis/p5e/sta_mcp.tcl" > "$o/sta.txt" 2>&1 &
        done
        wait
    done
    gzip -f "$R"/mcp/*/*/mcp.tcl ;;
report)
    python3 -I "$ROOT/tools/p5_results.py" "$R/new" "$LIB" "P5e results (new timing-driven ABC flow)" > "$R/new/RESULTS.md"
    python3 -I "$ROOT/tools/p5e_report.py" "$LIB" > "$R/COMPARE.md"
    { echo '# P5e critical paths, new flow, rtl-v2-final, 1 GHz netlists — NanGate45, not TSMC; pre-layout'
      echo
      echo 'Generated by `tools/p5_critical_path.py results/P5e/new <runs>` from `<run>/sta.txt` (no multicycle'
      echo 'exceptions). Which of these paths can be exercised in one cycle: `SUMMARY.md` and `COMPARE.md` section 5.'
      echo
      python3 -I "$ROOT/tools/p5_critical_path.py" results/P5e/new d16_m0_1000MHz d16_m1_1000MHz d64_m0_1000MHz \
          d64_m1_1000MHz d256_m0_1000MHz d256_m1_1000MHz; } > "$R/CRITICAL_PATH.md" ;;
*) echo "unknown step $step"; exit 2 ;;
esac; done
