"""Generate the repetitive tables of the implementation report (docs/synthesis_report/gen_*.tex).

Usage (from the repository root): python3 -I docs/synthesis_report/gen_tables.py

Every cell is a number macro \\R{key}; the keys are defined in docs/synthesis_report/macros.tex, which
tools/make_paper_macros.py --target synth writes from committed results files (each definition names its source file,
line, row and column). This script only lays the keys out in table rows, so a table cannot hold a number that has no
source: tools/paper_numbers_check.py --macros docs/synthesis_report rejects any digit outside \\R{} in these files, and
make_paper_macros.py fails on a key it does not define. Run order (Makefile): this script, then make_paper_macros.py,
then the number check, then latexmk.
"""
from pathlib import Path

OUT = Path(__file__).resolve().parent
HEAD = '% Generated by docs/synthesis_report/gen_tables.py. Do not edit by hand.\n'
DEPTHS = ('16', '64', '256')
NS = [(n, s) for n in ('v2', 'v3') for s in ('row0', 'row1M')]


def R(k):
    return f'\\R{{{k}}}'


def write(name, lines):
    (OUT / f'gen_{name}.tex').write_text(HEAD + '\n'.join(lines) + '\n')


def table(rows):
    return [' & '.join(r) + r' \\' for r in rows]


# P12: tightest period met / loosest failed, per version, mode and depth
write('p12_bracket', table(
    [[v, f'mode {m}'] + [f"{R(f'p12.b.{v}.{m}.{d}.met')} / {R(f'p12.b.{v}.{m}.{d}.fail')}" for d in DEPTHS]
     for v in ('v2', 'v3') for m in '01']))

# P12: area, cells and flip-flops at the relaxed period, v2 and v3, with the v3 - v2 area change
write('p12_area', table(
    [[R(f'sz.{d}'), f'mode {m}', R(f'sr.area.v2.{m}.{d}'), R(f'sr.area.v3.{m}.{d}'), R(f'p12.a.{d}.m{m}'),
      R(f'sr.cells.v2.{m}.{d}'), R(f'sr.cells.v3.{m}.{d}'), R(f'sr.ff.v2.{m}.{d}'), R(f'sr.ff.v3.{m}.{d}')]
     for d in DEPTHS for m in '01']))

# design: flip-flops of the Genus netlists in mode 0 and the pointer width added by v3
write('ff', table(
    [[R(f'sz.{d}'), R(f'sr.ff.v2.0.{d}'), R(f'sr.ff.v3.0.{d}'), R(f'p11.ff.{d}')] for d in DEPTHS]))

# open baseline: P5 to P5e Fmax by iteration and the flow noise
ITER = (('P5 baseline', 'p5'), ('P5b Stage-B tree, address flip-flops', 'p5b'), ('P5c Stage-A tree', 'p5c'),
        ('P5d hit-index tree (old flow)', 'p5d'), ('P5e same RTL, timing-driven flow', 'p5e'))
write('p5iter', table([[lab] + [R(f'{k}.f.{d}') for d in DEPTHS] for lab, k in ITER]) + [r'\midrule'] + table(
    [['Flow noise, old flow (\\%)'] + [R(f'p5d.noise.{d}.0') for d in DEPTHS],
     ['Flow noise, timing-driven flow (\\%)'] + [R(f'p5e.noise.{d}.0') for d in DEPTHS]]))

# open baseline: final v2 on the timing-driven flow
write('p5e', table(
    [[R(f'sz.{d}'), f'mode {m}'] + [R(f'p5e.{d}.{m}.{k}') for k in ('cells', 'ff', 'area', 'fmax', 'wns500')]
     for d in DEPTHS for m in '01']))

# open baseline: P8 power components
write('p8', table(
    [[R(f'sz.{d}')] + [R(f'p8.{d}.{k}') for k in ('ck', 'ffo', 'comb', 'sw', 'leak')] for d in DEPTHS]))

# P13 power before layout
write('p13', table(
    [[n, s, R(f'sr.p13.cyc.{n}.{s}'), R(f'p13.mW.{n}.{s}'), R(f'sr.p13.sw.{n}.{s}'), R(f'p13.E.{n}.{s}'),
      R(f'p13.reg.{n}.{s}'), R(f'p13.logic.{n}.{s}'), R(f'p13.cov.{n}.{s}')] for n, s in NS]))

# P15 final runs (depth 256 target-slack flow; depth 16 multi-row-fixed flow)
rows = [[f'v3, depth {R("sz.16")}', R('p15.d16.period'), R('sr.d16.s'), R('p15.d16.n'), R('sr.d16.h'),
         R('sr.d16.hn'), R('p15.d16.drc'), R('sr.d16.conn'), R('sr.d16.la'), R('sr.d16.core')]]
for v in ('v2', 'v3'):
    for pk, per in (('09', 'p15.fail'), ('10', 'p15.met'), ('11', 'p15.gls.period')):
        rows.append([f'{v}, depth {R("sz.256")}', R(per)] +
                    [R(f'p15f.{v}.{pk}.{k}') for k in ('s', 'sn', 'h', 'hn', 'drc')] + [R('p15.conn')] +
                    [R(f'p15f.{v}.{pk}.{k}') for k in ('la', 'core')])
write('p15', table(rows))

# P15 power after routing
write('p15pow', table(
    [[n, s, R(f'sr.p15.cyc.{n}.{s}'), R(f'p15.mW.{n}.{s}'), R(f'sr.p15.sw.{n}.{s}'), R(f'p15.E.{n}.{s}'),
      R(f'p15.reg.{n}.{s}'), R(f'p15.clk.{n}.{s}'), R(f'p15.logic.{n}.{s}')] for n, s in NS]))

# P16 corners: worst setup / hold slack per corner, and the derived slow-corner period
DES = (('v3, depth', 'sz.16', 'd16v3', '08', 'p15.d16.period', 'p16.dp.d16'),
       ('v2, depth', 'sz.256', 'd256v2', '10', 'p15.met', 'p16.dp.v2.10'),
       ('v3, depth', 'sz.256', 'd256v3', '10', 'p15.met', 'p16.dp.v3.10'),
       ('v2, depth', 'sz.256', 'd256v2', '11', 'p15.gls.period', 'p16.dp.v2.11'),
       ('v3, depth', 'sz.256', 'd256v3', '11', 'p15.gls.period', 'p16.dp.v3.11'))
write('p16', table(
    [[f'{lab} {R(dk)}', R(per)] + [f"{R(f'p16t.{k}.{pk}.{c}.s')} / {R(f'p16t.{k}.{pk}.{c}.h')}"
                                   for c in ('tt', 'ss', 'ff')] + [R(dp)]
     for lab, dk, k, pk, per, dp in DES]))

print('wrote', ', '.join(sorted(p.name for p in OUT.glob('gen_*.tex'))))
