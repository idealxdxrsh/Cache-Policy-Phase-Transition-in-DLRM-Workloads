"""Generate the LaTeX tables of the synthesis report from results/P7/TABLES.md (committed version) and git.

Usage: python3 -I docs/synthesis_report/gen_tables.py      (writes docs/synthesis_report/gen_*.tex)
Every rounded value is written as \\rnd{shown}{source}, where source is the exact TABLES.md string, so
tools/paper_numbers_check.py can verify it. Rounding: Fmax and area to integers, slack/delay to 3 decimals in ns,
flip-flop area share to 3 decimals, counts exact. Commit IDs come from git (rewritten history only).
"""
import re
import subprocess
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

ROOT = Path(subprocess.run(['git', 'rev-parse', '--show-toplevel'], capture_output=True, text=True,
                           check=True).stdout.strip())
OUT = ROOT / 'docs/synthesis_report'


def git(*a):
    return subprocess.run(['git', '-C', str(ROOT), *a], capture_output=True, text=True, check=True).stdout.strip()


TABLES = git('show', 'HEAD:results/P7/TABLES.md')
LINES = TABLES.splitlines()


def section(title, level='###'):
    """Lines after the heading that starts with `title`, up to the next heading of the same or higher level."""
    i = next(k for k, l in enumerate(LINES) if l.startswith(f'{level} {title}'))
    out = []
    for l in LINES[i + 1:]:
        if re.match(r'^#{1,%d} ' % len(level), l):
            break
        out.append(l)
    return out


def rows(lines):
    return [[c.strip() for c in l.strip().strip('|').split('|')] for l in lines
            if l.startswith('|') and not set(l) <= set('|-') and not l.startswith('|---')]


def rnd(v, k):
    v = v.replace(',', '')
    neg = v.startswith('-')
    a = v.lstrip('-+')
    shown = str(Decimal(a).quantize(Decimal(1).scaleb(-k), rounding=ROUND_HALF_UP))
    if k == 0:
        shown = f'{int(shown):,}'
    return ('$-$' if neg else '') + f'\\rnd{{{shown}}}{{{a}}}'


def tt(s):
    s = s.replace('\\', '').replace(' ', '')
    return '\\texttt{' + s.replace('_', '\\_') + '}'


def write(name, text):
    (OUT / name).write_text('% generated by docs/synthesis_report/gen_tables.py from results/P7/TABLES.md; do not edit\n'
                            + text + '\n')
    print('wrote', name)


# ---------------------------------------------------------------- per-iteration result tables
PH = [('PFive', 'P5: rtl-v2-baseline'), ('PFiveB', 'P5b: Stage-B'), ('PFiveC', 'P5c tree + copies'),
      ('PFiveD', 'P5d: hit_idx'), ('PFiveE', 'P5e: rtl-v2-final')]
out = []
for key, head in PH:
    sec = section(head)
    r = {(a[0], a[1], a[2]): a for a in rows(sec) if a[0].isdigit()}
    rng = next(l for l in sec if l.startswith('Flip-flop area share range'))
    body = []
    for d in ('16', '64', '256'):
        for m in ('0', '1'):
            g, h = r[d, m, '1000 MHz'], r[d, m, '500 MHz']
            fmax = rnd(g[9], 0) if not g[9].startswith('met') else 'met'
            w500 = 'met' if float(h[7]) >= 0 else rnd(h[7], 3)
            body.append(f'{d} & {m} & {g[3]} & {g[4]} & {rnd(g[5], 0)} & {rnd(g[6], 3)} & {fmax} & {rnd(g[7], 3)} & '
                        f'{w500} & {g[10]} / {h[10]} \\\\')
    out.append(f'\\newcommand{{\\tab{key}}}{{%\n\\begin{{tabular}}{{rrrrrrrrrr}}\n\\toprule\n'
               'Depth & Mode & Cells & FFs & Area & FF share & Fmax & WNS 1\\,GHz & WNS 500\\,MHz & Viol. \\\\\n'
               ' & & & & ($\\mu$m$^2$) & of area & (MHz) & (ns) & (ns) & 1G / 500M \\\\\n\\midrule\n'
               + '\n'.join(body) + '\n\\bottomrule\n\\end{tabular}}')
    lo, hi = re.search(r'([\d.]+)-([\d.]+)\.$', rng).groups()
    out.append(f'\\newcommand{{\\share{key}}}{{{rnd(lo, 3)}--{rnd(hi, 3)}}}')
write('gen_results.tex', '\n'.join(out))

# ---------------------------------------------------------------- noise floor
def noise(title):
    return {(a[0], a[1]): a for a in rows(section(title, '####')) if a[0].isdigit()}


old, new = noise('old flow (P5d)'), noise('P5e flow')
body = []
for d in ('16', '64', '256'):
    for m in ('0', '1'):
        o, n = old[d, m], new[d, m]
        body.append(f'{d} & {m} & {rnd(o[10], 0)}--{rnd(o[11], 0)} & {o[12].replace("%", chr(92) + "%")} & '
                    f'{rnd(n[10], 0)}--{rnd(n[11], 0)} & {n[12].replace("%", chr(92) + "%")} \\\\')
write('gen_noise.tex', '\\begin{tabular}{rrrrrr}\n\\toprule\n & & \\multicolumn{2}{c}{Old flow (P5d)} & '
      '\\multicolumn{2}{c}{Timing-driven flow (P5e)} \\\\\n\\cmidrule(lr){3-4}\\cmidrule(lr){5-6}\n'
      'Depth & Mode & Fmax min--max (MHz) & Spread & Fmax min--max (MHz) & Spread \\\\\n\\midrule\n'
      + '\n'.join(body) + '\n\\bottomrule\n\\end{tabular}')

# ---------------------------------------------------------------- critical paths
out = []
for key, title in (('BaseSixteen', 'P5 baseline, depth 16'), ('BaseTwoFiveSix', 'P5 baseline, depth 256'),
                   ('FinalSixteen', 'P5e final, depth 16'), ('FinalTwoFiveSix', 'P5e final, depth 256')):
    sec = section(title, '####')
    txt = '\n'.join(sec)
    sp = re.search(r'start `([^`]+)` \(Q = `([^`]+)`\), end `([^`]+)` \(Q = `([^`]+)`\)', txt).groups()
    cells, arr, setup, slack = re.search(r'cells on path (\d+) .*?data arrival ([\d.]+) ns; setup ([\d.]+) ns; '
                                         r'slack (\S+) ns', txt).groups()
    nb, bd, lr, ld, nbd = re.search(r'buffers (\d+), ([\d.]+) ns; longest run of consecutive buffers (\d+) cells, '
                                    r'([\d.]+) ns; non-buffer cells ([\d.]+) ns', txt).groups()
    ct = [a for a in rows(sec) if a[0] != 'cell type'][:6]
    out.append(f'\\newcommand{{\\cpStart{key}}}{{{tt(sp[1])}}}\\newcommand{{\\cpEnd{key}}}{{{tt(sp[3])}}}')
    out.append(f'\\newcommand{{\\cpSum{key}}}{{{cells} & {rnd(arr, 3)} & {rnd(slack, 3)} & {nb} / {rnd(bd, 3)} & '
               f'{lr} / {rnd(ld, 3)} & {rnd(nbd, 3)}}}')
    out.append(f'\\newcommand{{\\cpTypes{key}}}{{' + '; '.join(f'{c[0].replace("_", chr(92) + "_")} {c[1]}$\\times$, '
                                                            f'{rnd(c[2], 3)}' for c in ct) + '}')
write('gen_paths.tex', '\n'.join(out))

# ---------------------------------------------------------------- multicycle cross-check
r = {(a[0], a[1]): a for a in rows(section('Multicycle cross-check')) if a[0] in ('old', 'new')}
body = []
for d in ('16', '64', '256'):
    for m in ('0', '1'):
        for f in ('1000', '500'):
            run = f'd{d}_m{m}_{f}MHz'
            o, n = r['old', run], r['new', run]
            cell = lambda v: '0' if float(v) == 0 else (('$-$' if v.startswith('-') else '') + v.lstrip('-') if abs(float(v)) < 0.0005 else rnd(v, 3))
            body.append(f'{d} & {m} & {f} & {cell(o[2])} & {cell(o[3])} & {cell(n[2])} & {cell(n[3])} \\\\')
mx = next(l for l in section('Multicycle cross-check') if l.startswith('Largest WNS change'))
mo, mn = re.search(r'old flow ([\d.]+) ns, new flow ([\d.]+) ns', mx).groups()
write('gen_mcp.tex', '\\newcommand{\\mcpTable}{%\n\\begin{tabular}{rrrrrrr}\n\\toprule\n & & & '
      '\\multicolumn{2}{c}{Old flow WNS (ns)} & \\multicolumn{2}{c}{Timing-driven WNS (ns)} \\\\\n'
      '\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}\nDepth & Mode & MHz & without & with & without & with \\\\\n\\midrule\n'
      + '\n'.join(body) + '\n\\bottomrule\n\\end{tabular}}\n'
      f'\\newcommand{{\\mcpMaxOld}}{{{rnd(mo, 3)}}}\\newcommand{{\\mcpMaxNew}}{{{rnd(mn, 3)}}}')

# ---------------------------------------------------------------- gate-level lockstep and unit tests
lk = rows(section('P5f lockstep RTL vs netlist'))
body = []
for a in lk:
    if not a[0].startswith('d'):
        continue
    d, m, f = re.match(r'd(\d+)_m(\d)_(\d+)MHz', a[0]).groups()
    body.append(f'{d} & {m} & {f} & {a[1]} & {a[3]} & {a[4]} & {a[5]} & {a[6].replace(" / ", "/")} & {a[8]} & {a[9]} \\\\')
write('gen_gls.tex', '\\begin{tabular}{rrrrrrrrrr}\n\\toprule\nDepth & Mode & MHz & Cycles & Hits & Misses & '
      'Mismatch & X (gl/rtl) & vvp wall & Peak RSS (kB) \\\\\n\\midrule\n' + '\n'.join(body)
      + '\n\\bottomrule\n\\end{tabular}')
ut = rows(section('P5f unit testbench'))
body = []
for a in ut:
    if not a[0].startswith('d'):
        continue
    d, m, f = re.match(r'd(\d+)_m(\d)_(\d+)MHz', a[0]).groups()
    res = 'pass' if a[2] == 'ALL TESTS PASSED' else 'FAIL'
    body.append(f'{d} & {m} & {f} & {a[1]} & {res} & {a[3]} & {a[4]} \\\\')
write('gen_unit.tex', '\\begin{tabular}{rrrlrll}\n\\toprule\nDepth & Mode & MHz & Where & Result & Compile & Run \\\\\n'
      '\\midrule\n' + '\n'.join(body) + '\n\\bottomrule\n\\end{tabular}')

# ---------------------------------------------------------------- commit IDs (rewritten history) and file index
def last(path):
    return git('log', '-1', '--format=%h', '--', path)


def added(path):                                  # commit that first added the file (or any file under a directory)
    return git('log', '--diff-filter=A', '--format=%h', '--', path).splitlines()[-1]


cid = {'Final': git('rev-parse', '--short', 'rtl-v2-final^{commit}'),
       'Base': git('rev-parse', '--short', 'rtl-v2-baseline^{commit}'),
       'PfiveB': added('results/P5b/RESULTS.md'), 'PfiveC': added('results/P5c/tree_copies/RESULTS.md'),
       'Flow': added('results/P5e/new/RESULTS.md'), 'Gls': added('results/P5f_gls/cluster/'),
       'Tables': last('results/P7/TABLES.md')}
idx = [('results/P5/RESULTS.md', 'P5 baseline, all runs'), ('results/P5/SOURCES.md', 'toolchain and liberty record'),
       ('results/P5/CRITICAL_PATH.md', 'baseline critical paths'), ('results/P5b/RESULTS.md', 'P5b runs'),
       ('results/P5c/tree_copies/RESULTS.md', 'P5c runs (kept variant)'), ('results/P5c/tree_only/RESULTS.md', 'P5c tree only'),
       ('results/P5d/RESULTS.md', 'P5d runs (rtl-v2-final, old flow)'), ('results/P5d/NOISE.md', 'old-flow noise floor'),
       ('results/P5d/mutation.txt', 'mutation test of the final RTL'), ('results/P5e/new/RESULTS.md', 'P5e runs (final)'),
       ('results/P5e/COMPARE.md', 'flow comparison, noise, multicycle'), ('results/P5e/CRITICAL_PATH.md', 'final critical paths'),
       ('results/P5f_gls/CELLCHECK.md', 'cell-model check'), ('results/P5f_gls/COVERAGE.md', 'cell-type coverage'),
       ('results/P5f_gls/equiv/', 'depth-16 equivalence'), ('results/P5f_gls/cluster/', 'cluster gate-level runs'),
       ('results/P5f_gls/sim/', 'local gate-level unit tests'), ('results/P5f_gls/SUMMARY.md', 'gate-level summary'),
       ('results/P7/TABLES.md', 'all tables, generated'), ('results/COMMIT_MAP.md', 'old-to-new commit IDs')]
body = [f'\\src{{{p}}} & {what} & \\texttt{{{added(p)}}} & \\texttt{{{last(p)}}} \\\\' for p, what in idx]
write('gen_ids.tex', '\n'.join(f'\\newcommand{{\\cid{k}}}{{\\texttt{{{v}}}}}' for k, v in cid.items()) + '\n'
      '\\newcommand{\\fileIndex}{%\n\\begin{tabular}{>{\\raggedright\\arraybackslash}p{0.44\\textwidth}>{\\raggedright\\arraybackslash}p{0.245\\textwidth}ll}\n\\toprule\n'
      'File & Content & Added in & Last changed \\\\\n\\midrule\n' + '\n'.join(body) + '\n\\bottomrule\n\\end{tabular}}')
